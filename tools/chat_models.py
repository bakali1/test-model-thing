# stop head if it is long enough. Calibrated on the SAME protocol used to
# calibrate the degeneracy arms (2000 bytes, 3 prompts, 3 seeds), where the
# KNOWN-GOOD incumbent still produces a zero-firing generation:
#     incumbent  2/9 generations with 0 firings, 0.83/kB overall
#     600k       9/9 generations with 0 firings, 0.00/kB
