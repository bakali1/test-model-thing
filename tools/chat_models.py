def main(argv=None):
    ap = argparse.ArgumentParser(
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description=__doc__,
        epilog=("CAVEAT: with a single fixed seed, different prompts can yield "
                "near-identical continuations, because the next-byte "
                "distributions of very different prompts differ by at most "
                "~0.13 in probability. Cross-prompt comparison is therefore "
                "WEAK evidence; the degeneracy metrics are the real signal. "
                "Use --seeds with several values before calling anything a "
                "result."))
    ap.add_argument("--n", type=int, default=DEFAULT_N,
                    help=f"bytes to generate (default: {DEFAULT_N}; a short "
                         "run cannot detect a dead stop head or a late loop)")
    ap.add_argument("--temp", type=float, default=None,
                    help="override sampling temperature (default: model's)")
    ap.add_argument("--prompt", choices=("ts", "ne", "novel", "all"),
                    default="all")
    ap.add_argument("--prompt-file", default=None,
                    help="read a raw prompt from PATH as UTF-8 bytes; when "
                         "given it replaces --prompt")
    ap.add_argument("--set", default=None,
                    help="comma-separated label=path pairs (whitespace is "
                         "stripped; empty labels/paths and duplicate labels "
                         "are errors)")
    ap.add_argument("--set-glob", default=None,
                    help="discover checkpoints by glob, e.g. "
                         "'runs/*/*/results/*_t*.npz'; label = file stem")
    ap.add_argument("--seed", type=int, default=0,
                    help="single sampling seed (same seed for every model so "
                         "the draws line up). Ignored when --seeds is given.")
    ap.add_argument("--seeds", default=None,
                    help="comma-separated seeds, e.g. 0,1,2,3,4,5 (default: "
                         "--seed alone, which preserves the single-seed "
                         "behaviour)")
    ap.add_argument("--json", default=None,
                    help="write the full result set (every metric, seed, "
                         "model, prompt bytes and checkpoint metadata) here")
    args = ap.parse_args(argv)

    # ---- model set -------------------------------------------------------
    try:
        if args.set or args.set_glob:
            models = []
            if args.set:
                models += parse_set(args.set)
            if args.set_glob:
                models += parse_set_glob(args.set_glob)
            _check_duplicate_labels(models)
            source = "explicit"
        else:
            models = list(DEFAULT_SET)
            source = "DEFAULT_SET"
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    present, skipped = resolve_models(models)
    if not present:
        print(f"error: no checkpoints available from {source}. "
              f"tried {len(models)} path(s):", file=sys.stderr)
        for s in skipped:
            print(f"  {s['label']}: {s['path']}  -- {s['reason']}", file=sys.stderr)
        print("pass --set label=path or --set-glob 'runs/*/*/results/*_t*.npz'",
              file=sys.stderr)
        return 2
    if skipped:
        print(f"note: {len(skipped)} of {len(models)} model(s) in {source} "
              "are not available in this checkout and will NOT be measured; "
              "see the SKIPPED summary at the end.")

    # ---- prompts ---------------------------------------------------------
    prompts = []
    if args.prompt_file:
        try:
            with open(args.prompt_file, "rb") as f:
                raw = f.read()
        except OSError as e:
            print(f"error: --prompt-file {args.prompt_file}: {e}",
                  file=sys.stderr)
            return 2
        prompts.append((f"file prompt: {args.prompt_file}", raw))
    else:
        if args.prompt in ("ts", "all"):
            prompts.append(("in-domain (TinyStories opening)", PROMPT_TS))
        if args.prompt in ("ne", "all"):
            prompts.append(("transfer (neutral English opening)", PROMPT_NE))
        if args.prompt in ("novel", "all"):
            prompts.append(("narrative prose opening (FS-N's own domain)",
                            PROMPT_NOVEL))

    # ---- seeds -----------------------------------------------------------
    if args.seeds:
        try:
            seeds = [int(s.strip()) for s in args.seeds.split(",")
                     if s.strip() != ""]
        except ValueError:
            print(f"error: --seeds must be comma-separated integers, got "
                  f"{args.seeds!r}", file=sys.stderr)
            return 2
        if not seeds:
            print("error: --seeds is empty", file=sys.stderr)
            return 2
    else:
        seeds = [args.seed]          # preserves the historical single-seed run

    print(f"chat_models: n={args.n} temp={args.temp if args.temp is not None else 'model'} "
          f"seeds={seeds} prompts={len(prompts)} models={len(present)}")
    print(f"degeneracy rule: whitespace run>={DEGEN_WS_RUN} or "
          f"unique_8gram<{DEGEN_U8_RATIO} or (top 8-gram>="
          f"{100 * DEGEN_REP8_FRAC:.0f}% of output AND >={DEGEN_REP8_MIN}x) or a "
          f"{DEGEN_TAIL_N}-gram repeated >={DEGEN_TAIL_REPEAT}x in the last "
          f"{DEGEN_TAIL_WINDOW} bytes; non-terminating is separate (0 stop "
          f"firings in >={NONTERM_MIN_BYTES} bytes)")

    # Verify every digest BEFORE generating anything: a tampered checkpoint
    # must abort the run, not be discovered after two minutes of sampling.
    digests = {}
    for label, path in present:
        digests[label] = verify_digest(path)

    # ---- run -------------------------------------------------------------
    model_rows = []
    for label, path in present:
        digest, verified = digests[label]
        m, info = load_model(path)
        print(f"\n### {label}  {path}")
        print(f"    t={info['t']:,}  B={info['B']}  ring_k={info['ring_k']}  "
              f"bytes_seen={info['bytes_seen']:,}  dim={info['dim']}  "
              f"layers={info['layers']}  "
              f"sha256={digest + '…' if digest else 'NO SIDECAR (unverified)'}")

        prompt_rows = []
        for title, prompt in prompts:
            print("\n" + "=" * 78)
            print(f"{label} | {title}")
            print(f'prompt: "{escape(prompt)}"')
            print("=" * 78)
            rows = []
            for seed in seeds:
                out, stops, dt, ent, eff_t = generate(m, prompt, args.n,
                                                      args.temp, seed)
                met = degeneracy_metrics(out, stops, ent, eff_t, dt)
                met["seed"] = seed
                met["text"] = out.decode("utf-8", errors="replace")
                met["text_b64"] = base64.b64encode(out).decode()
                rows.append(met)
                print(f"  seed {seed}  {print_per_generation(met)}  {dt:.1f}s")
                for ln in wrap(escape(out)):
                    print(ln)
            agg = aggregate(rows)
            print(f"  -- {label} / {title} across seeds:")
            print_metric_table(agg, seeds)
            prompt_rows.append({"title": title, "prompt": prompt,
                                "agg": agg, "rows": rows})

        model_rows.append({
            "label": label,
            "path": os.path.relpath(path, HERE) if path.startswith(HERE)
                    else path,
            "t": info["t"],
            "B": info["B"],
            "ring_k": info["ring_k"],
            "bytes_seen": info["bytes_seen"],
            "dim": info["dim"],
            "layers": info["layers"],
            "digest": digest,
            "digest_full": read_sidecar(path),
            "digest_verified": verified,
            "agg": aggregate([r for pr in prompt_rows for r in pr["rows"]]),
            "prompts": [{"title": pr["title"],
                         "prompt_bytes_hex": pr["prompt"].hex(),
                         "prompt_bytes_b64": base64.b64encode(
                             pr["prompt"]).decode(),
                         "agg": pr["agg"],
                         "seeds": [{k: v for k, v in r.items()}
                                   for r in pr["rows"]]}
                        for pr in prompt_rows],
        })

    print_skipped(skipped)
    print_summary(model_rows)
    print_rankings(model_rows)

    if args.json:
        payload = {
            "tool": "tools/chat_models.py",
            "generated_utc": datetime.datetime.now(
                datetime.timezone.utc).isoformat(timespec="seconds"),
            "n": args.n,
            "temp": args.temp,
            "seeds": seeds,
            "prompts": [{"title": t,
                         "bytes_hex": b.hex(),
                         "bytes_b64": base64.b64encode(b).decode(),
                         "text": b.decode("utf-8", errors="replace")}
                        for t, b in prompts],
            "degeneracy_rule": {
                "whitespace_run_gte": DEGEN_WS_RUN,
                "unique_8gram_lt": DEGEN_U8_RATIO,
                "rep_8gram_frac_gte": DEGEN_REP8_FRAC,
                "rep_8gram_top_gte": DEGEN_REP8_MIN,
                "tail_ngram": DEGEN_TAIL_N,
                "tail_window": DEGEN_TAIL_WINDOW,
                "tail_repeat_gte": DEGEN_TAIL_REPEAT,
                "nonterminating_min_bytes": NONTERM_MIN_BYTES,
                "stop_kb_natural_reference": STOP_KB_REFERENCE,
            },
            "models": model_rows,
            "summary": [summary_row(r) for r in model_rows],
            "skipped": skipped,
        }
        with open(args.json, "w") as f:
            json.dump(payload, f, indent=2, sort_keys=False)
        print(f"\nwrote {args.json}")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
