def mean(vals):
    vals = [v for v in vals if v == v]
    return sum(vals) / len(vals) if vals else float("nan")


def aggregate(rows):
    """Collapse a list of per-generation metric dicts into one summary dict."""
    if not rows:
        return {}
    nbytes = sum(r["bytes"] for r in rows)
    agg = {"generations": len(rows),
           "bytes": nbytes,
           "degenerate": sum(1 for r in rows if r["degenerate"]),
           "nonterminating": sum(1 for r in rows if r["nonterminating"]),
           "stop_hits": sum(r["stop_hits"] for r in rows),
           "max_run_newlines": max(r["max_run_newlines"] for r in rows),
           "max_run_ws": max(r["max_run_ws"] for r in rows),
           "mean_entropy": mean([r["mean_entropy"] for r in rows]),
           "effective_temp": mean([r["effective_temp"] for r in rows])}
    # Normalized liveness: firings per 1000 generated bytes, so the number is
    # comparable across models, prompts and --n. Natural prose: ~13-17.
    agg["stop_per_kB"] = (1000.0 * agg["stop_hits"] / nbytes
                          if nbytes else float("nan"))
    for f in METRIC_FIELDS + ("mean_entropy", "effective_temp"):
        agg[f + "_mean"] = mean([r[f] for r in rows])
        agg[f + "_min"] = min(r[f] for r in rows)
        agg[f + "_max"] = max(r[f] for r in rows)
    return agg


def agg_cells(agg, field):
    """'mean [min..max]' string for a metric field (used by ad-hoc reporting)."""
    return (f"{agg[field + '_mean']:.3g} [{agg[field + '_min']:g}"
            f"..{agg[field + '_max']:g}]")


