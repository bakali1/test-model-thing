# ---------------------------------------------------------------------------
# Metrics. Pure functions over bytes: no model, no RNG, no I/O. This is what
# tests/check_chat_metrics.py exercises directly.
# ---------------------------------------------------------------------------
def max_run_of(b, pred):
    """Longest run of consecutive bytes satisfying pred."""
    best = run = 0
    for c in b:
        if pred(c):
            run += 1
            if run > best:
                best = run
        else:
            run = 0
    return best


def max_run_newlines(b):
    """Longest run of consecutive b"\\n" in b (0 if there is no newline)."""
    return max_run_of(b, lambda c: c == 0x0A)


# Whitespace = space, tab, CR, LF. Newlines alone are not enough: the 400k
# checkpoint of the long run collapses into runs of SPACES (177 in a row) and
# scores 0/9 degenerate under a newline-only rule.
WHITESPACE = (0x20, 0x09, 0x0A, 0x0D)


def max_run_whitespace(b):
    """Longest run of ANY whitespace byte (newline, space, tab, CR)."""
    return max_run_of(b, lambda c: c in WHITESPACE)


def unique_byte_count(b):
    """Number of distinct byte values in b."""
    return len(set(b))


def ngram_stats(b, n):
    """(total, distinct, top_count) over all n-grams of b.

    Short inputs (len(b) < n) have no n-grams: total=distinct=top=0.
    """
    b = bytes(b)
    total = len(b) - n + 1
    if total <= 0:
        return 0, 0, 0
    counts = Counter(b[i:i + n] for i in range(total))
    return total, len(counts), max(counts.values())


def unique_ngram_ratio(b, n):
    """distinct n-grams / total n-grams; 1.0 when there are no n-grams."""
    total, distinct, _ = ngram_stats(b, n)
    return 1.0 if total == 0 else distinct / total


def top_ngram_freq(b, n):
    """Count of the single most common n-gram in b (0 if none)."""
    return ngram_stats(b, n)[2]


def tail_ngram_top(b, n=DEGEN_TAIL_N, window=DEGEN_TAIL_WINDOW):
    """Most common n-gram inside the last `window` bytes of b."""
    b = bytes(b)
    tail = b[-window:] if len(b) > window else b
    return top_ngram_freq(tail, n)


def is_degenerate(b):
    """The four documented degeneracy arms, in one place.

    1. whitespace run >= DEGEN_WS_RUN
    2. unique_8gram ratio < DEGEN_U8_RATIO
    3. most common 8-gram >= DEGEN_REP8_FRAC of the output AND >= DEGEN_REP8_MIN
    4. a 4-gram repeated >= DEGEN_TAIL_REPEAT x in the last DEGEN_TAIL_WINDOW
    """
    b = bytes(b)
    if max_run_whitespace(b) >= DEGEN_WS_RUN:
        return True
    if unique_ngram_ratio(b, 8) < DEGEN_U8_RATIO:
        return True
    t8, _, top8 = ngram_stats(b, 8)
    if t8 and top8 >= DEGEN_REP8_MIN and top8 / t8 >= DEGEN_REP8_FRAC:
        return True
    if tail_ngram_top(b) >= DEGEN_TAIL_REPEAT:
        return True
    return False


def is_nonterminating(out, stop_hits):
    """True if the stop head never fired over a long enough generation.

    Separate from degeneracy: a drifting model that never stops repeats little
    and stays locally diverse, so it can look clean on every degeneracy arm.
    """
    return int(stop_hits) == 0 and len(bytes(out)) >= NONTERM_MIN_BYTES


def degeneracy_metrics(out, stop_hits=0, mean_entropy=float("nan"),
                      effective_temp=float("nan"), secs=0.0):
    """Every documented metric for one generation, as a flat dict."""
    b = bytes(out)
    t4, d4, top4 = ngram_stats(b, 4)
    t8, d8, top8 = ngram_stats(b, 8)
    return {
        "bytes": len(b),
        "max_run_newlines": max_run_newlines(b),
        "max_run_ws": max_run_whitespace(b),
        "unique_bytes": unique_byte_count(b),
        "unique_4gram": 1.0 if t4 == 0 else d4 / t4,
        "unique_8gram": 1.0 if t8 == 0 else d8 / t8,
        "rep_4gram_top": top4,
        "rep_8gram_top": top8,
        "rep_4gram_frac": 0.0 if t4 == 0 else top4 / t4,
        "rep_8gram_frac": 0.0 if t8 == 0 else top8 / t8,
        "tail_4gram_top": tail_ngram_top(b),
        "degenerate": is_degenerate(b),
        "nonterminating": is_nonterminating(b, stop_hits),
        "stop_hits": int(stop_hits),
        "mean_entropy": float(mean_entropy),
        "effective_temp": float(effective_temp),
        "secs": float(secs),
    }


METRIC_FIELDS = ("max_run_newlines", "max_run_ws", "unique_bytes",
                 "unique_4gram", "unique_8gram", "rep_4gram_top",
                 "rep_8gram_top", "rep_4gram_frac", "rep_8gram_frac",
                 "tail_4gram_top")


# ---------------------------------------------------------------------------
# Model-set specification. Every failure is loud: a silently shortened set
# looks like a result.
# ---------------------------------------------------------------------------
def _check_duplicate_labels(models):
    seen = {}
    for lab, path in models:
        if lab in seen:
            raise ValueError(
                f"duplicate model label {lab!r}: {seen[lab]!r} and {path!r}; "
                "labels must be unique so the summary table is unambiguous")
        seen[lab] = path
    return models


def parse_set(spec):
    """Parse `--set "label=path, label2=path2"`.

    Whitespace around every element is stripped. An empty label, an empty
    path, an element with no "=", or a duplicate label is an error, not a
    silently dropped entry. A label containing a comma cannot be expressed in
    this syntax and now fails loudly instead of becoming two models.
    """
    if spec is None or not spec.strip():
        raise ValueError("--set: empty specification")
    models = []
    for part in spec.split(","):
        item = part.strip()
        if not item:
            raise ValueError(f"--set: empty element in {spec!r}")
        if "=" not in item:
            raise ValueError(f"--set: {item!r} is not label=path")
        lab, _, path = item.partition("=")
        lab, path = lab.strip(), path.strip()
        if not lab:
            raise ValueError(f"--set: empty label in {item!r}")
        if not path:
            raise ValueError(f"--set: empty path for label {lab!r}")
        models.append((lab, path))
    if not models:
        raise ValueError("--set: no models given")
    return _check_duplicate_labels(models)


def parse_set_glob(pattern):
    """Discover checkpoints from a glob (e.g. 'runs/*/*/results/*_t*.npz').

    The label is the file stem, so runs/<date>/<run>/results/X_t123.npz
    becomes "X_t123". Sorted for reproducible output.
    """
    if pattern is None or not pattern.strip():
        raise ValueError("--set-glob: empty pattern")
    hits = sorted(p for p in glob.glob(pattern.strip()) if os.path.isfile(p))
    if not hits:
        raise ValueError(f"--set-glob: no files match {pattern!r}")
    models = [(os.path.splitext(os.path.basename(p))[0], p) for p in hits]
    return _check_duplicate_labels(models)


def resolve_models(models):
    """Split into (present, skipped). Skipped is reported once, at the end."""
    present, skipped = [], []
    for lab, path in models:
        if not os.path.exists(path):
            reason = "file not found"
        elif not os.path.isfile(path):
            reason = "not a regular file"
        elif os.path.getsize(path) == 0:
            reason = "empty file"
        else:
            present.append((lab, path))
            continue
        skipped.append({"label": lab, "path": path, "reason": reason})
    return present, skipped


