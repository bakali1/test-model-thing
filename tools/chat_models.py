def sha256_file(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(chunk), b""):
            h.update(block)
    return h.hexdigest()


def read_sidecar(path):
    """Digest from a '<name>.npz.sha256' sidecar, or None if there is none.

    sha256sum format: "<hex>  <name>", with optional trailing "# run_id ..."
    comments. The digest is taken from the first token whatever name it
    carries, so a checkpoint copied/renamed is still verified rather than
    silently skipped. A sidecar that exists but carries no 64-hex digest is
    an error: an unverifiable checkpoint must not be reported as verified.
    """
    side = path + ".sha256"
    if not os.path.exists(side):
        return None
    with open(side) as f:
        txt = f.read().split()
    hexish = set("0123456789abcdefABCDEF")
    if not txt or len(txt[0]) != 64 or not set(txt[0]) <= hexish:
        raise ValueError(f"sidecar {side} exists but carries no sha256 digest")
    return txt[0].lower()


def verify_digest(path, prefix_len=12):
    """Return (digest_prefix, verified) for path; hard-fail on a MISMATCH."""
    expected = read_sidecar(path)
    if expected is None:
        return None, False
    got = sha256_file(path)
    if got != expected:
        raise SystemExit(
            f"FATAL: sha256 MISMATCH for {path}\n"
            f"  sidecar: {expected}\n"
            f"  on disk: {got}\n"
            "  refusing to report metrics for a checkpoint that is not the one "
            "that was measured.")
    return got[:prefix_len], True


def checkpoint_info(path):
    """Metadata that distinguishes two checkpoints beyond t."""
    with np.load(path) as d:
        files = d.files

        def scalar(key, default=-1):
            if key not in files:
                return default
            return int(np.ravel(d[key])[0])

        dim = int(d["embed"].shape[1])
        layers = 1 + max((int(k.split(".")[0].replace("layer", ""))
                          for k in files
                          if k.startswith("layer") and k.endswith(".W")),
                         default=0)
        t = scalar("t")
        b = scalar("B")
        ring_k = scalar("ring_k")
        nbytes = scalar("bytes")
    if t >= 0 and nbytes < 0:
        nbytes = t * (b if b > 0 else 1)
    return {"dim": dim, "layers": layers, "t": t, "B": b, "ring_k": ring_k,
            "bytes_seen": nbytes}


# ---------------------------------------------------------------------------
# Generation. Read-only with respect to the checkpoint: load() copies params
# out of the npz and nothing here ever saves.
# ---------------------------------------------------------------------------
def load_model(path):
    info = checkpoint_info(path)
    numpy_port.rng = np.random.default_rng(0)   # constructor draws are unused
    m = numpy_port.Model(dim=info["dim"], layers=info["layers"])
    m.load(path)
    return m, info


def generate(m, prompt, n, temp=None, seed=0):
    """Generate n bytes from a cold (zeroed) state. Same seed => same draws."""
    if temp is not None:
        m.temp = temp
    m.new_states(1)          # zero memory: show the weights cold
    numpy_port.rng = np.random.default_rng(seed)   # same draws for every model
    out = bytearray(prompt)
    stops = 0
    ent_sum = 0.0
    eff_t = float("nan")
    t0 = time.time()
    for _ in range(n):
        # Mirror sample()'s entropy->temperature schedule so the report can
        # state the regime: when entropy is HIGH the temperature COLLAPSES
        # (0.75 * (1 - 0.75*1.0) = 0.19), i.e. near-greedy. Saying so is the
        # difference between "this is what the model believes" and "this is
        # what the sampler did".
        enc = m.embed[out[-1]]
        x = enc[None, :]
        for l in m.layers:
            x, ns, _, _ = l.forward(enc.reshape(1, -1), x, l.states[0:1])
            l.states[0:1] = ns
        logits = x[0] @ m.Wd.T + m.bd
        pr = np.exp(logits - logits.max())
        pr /= pr.sum()
        ent = float(-(pr * np.log(pr + 1e-8)).sum() / np.log(256.0))
        ent_sum += ent
        eff_t = max(0.1, m.temp * (1.0 - m.temp * ent))
        c = m.sample(logits)
        stop = float(np.asarray(x[0] @ m.Ws + m.bs).ravel()[0])
        stop = 1.0 / (1.0 + np.exp(-stop))
        if stop > 0.5:
            stops += 1
        out.append(c)
    return bytes(out[len(prompt):]), stops, time.time() - t0, ent_sum / max(n, 1), eff_t


# ---------------------------------------------------------------------------
# Rendering. Bytes are escaped so a wrapped line can never be misread: a real
# newline is printed as \n, never as a line break inside the sample.
# ---------------------------------------------------------------------------
def escape(b):
    """Bytes -> one line of readable text with control bytes made visible.

    Invalid UTF-8 becomes \\xNN rather than U+FFFD, so a byte-level defect is
    visible as a byte-level defect.
    """
    s = b.decode("utf-8", errors="backslashreplace")
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20 or o == 0x7F:
            out.append("\\x%02x" % o)
        else:
            out.append(ch)
    return "".join(out)


def wrap(text, width=TEXT_WIDTH, indent="    "):
    lines = []
    for i in range(0, len(text), width):
        lines.append(indent + text[i:i + width])
    return lines or [indent]


def fmt_float(x, nd=3):
    if x != x:                      # NaN
        return "n/a"
    return f"{x:.{nd}f}"


