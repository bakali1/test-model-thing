def print_per_generation(metrics):
    return (f"nl<={metrics['max_run_newlines']:<3d} "
            f"ws<={metrics['max_run_ws']:<3d} "
            f"uB={metrics['unique_bytes']:<3d} "
            f"u8={metrics['unique_8gram']:.2f} "
            f"rep8={metrics['rep_8gram_top']:<3d} "
            f"({100 * metrics['rep_8gram_frac']:4.1f}%) "
            f"stops={metrics['stop_hits']:<3d} "
            f"ent={fmt_float(metrics['mean_entropy'], 2)} "
            f"effT={fmt_float(metrics['effective_temp'], 2)}"
            f"{'  DEGENERATE' if metrics['degenerate'] else ''}"
            f"{'  NON-TERMINATING' if metrics['nonterminating'] else ''}")


