#!/usr/bin/env python3
"""Generate the three from-scratch corpus arms (FS-W / FS-N / FS-L).

Emits `colab_fs_<arm>.py`: a self-contained script that rents a T4, downloads
its corpus IN-SESSION, trains a model FROM t=0 for a fixed wall-clock budget,
and pushes the final checkpoint to the private hub.

    .venv/bin/python make_fs_bundle.py          # writes all three
    colab run --gpu T4 --timeout 4200 colab_fs_w.py

Why from scratch
----------------
The live checkpoint (t=64,747) was trained on TinyStories. A continuation A/B
of "wikistories vs novels" is therefore confounded: arm W is *more of what the
model already knows*. Starting every arm at t=0 from a bit-identical seeded
init (--seed 0) makes the corpus the only axis that differs.

The three arms
--------------
  W  TinyStories  (roneneldan/TinyStories) -- the incumbent's actual training
     data. Fetched at a byte OFFSET beyond the locally staged 165 MB so the
     ruler's decontaminated eval split cannot overlap it.
  N  Gutenberg    (Despina/project_gutenberg, fiction_books, MIT) -- narrative
     prose, the "does coherence grow long-memory dims?" arm.
  L  Layered mix  (Gutenberg + FineWeb-Edu score>=3 + UltraChat) -- the
     strategic candidate: does a multi-domain mix beat any single domain?

Each arm is budgeted at one hour of GPU wall clock. Training length is derived
from a measured in-session rate, not guessed, so the budget is respected on
whatever hardware Colab hands us.
"""
import os
import stat
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

