#!/usr/bin/env python3
"""Generate the three from-scratch corpus arms (FS-W / FS-N / FS-L).

Emits `colab_fs_<arm>.py`: a self-contained script that rents a T4, downloads
its corpus IN-SESSION, trains a model FROM t=0 for a fixed wall-clock budget,
and pushes the final checkpoint to the private hub.

    .venv/bin/python make_fs_bundle.py          # writes all three
    colab run --gpu T4 --timeout 4200 colab_fs_w.py

Why from scratch
----------------
The live checkpoint (t=64,747) was trained on TinyStories. A continuation A/B
of "wikistories vs novels" is therefore confounded: arm W is *more of what the
model already knows*. Starting every arm at t=0 from a bit-identical seeded
init (--seed 0) makes the corpus the only axis that differs.

The three arms
--------------
  W  TinyStories  (roneneldan/TinyStories) -- the incumbent's actual training
     data. Fetched at a byte OFFSET beyond the locally staged 165 MB so the
     ruler's decontaminated eval split cannot overlap it.
  N  Gutenberg    (Despina/project_gutenberg, fiction_books, MIT) -- narrative
     prose, the "does coherence grow long-memory dims?" arm.
  L  Layered mix  (Gutenberg + FineWeb-Edu score>=3 + UltraChat) -- the
     strategic candidate: does a multi-domain mix beat any single domain?

Each arm is budgeted at one hour of GPU wall clock. Training length is derived
from a measured in-session rate, not guessed, so the budget is respected on
whatever hardware Colab hands us.
"""
import os
import stat
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

TINYSTORIES = ("https://huggingface.co/datasets/roneneldan/TinyStories/"
               "resolve/main/TinyStories-train.txt")

ARMS = {
    "w": dict(
        name="FS-W",
        question="incumbent data (TinyStories), clean from t=0",
        kind="tinystories",
    ),
    "n": dict(
        name="FS-N",
        question="narrative prose: does it grow long-memory dims?",
        kind="gutenberg",
        layers="A",
    ),
    "l": dict(
        name="FS-L",
        question="layered mix: does multi-domain beat single-domain?",
        kind="gutenberg",
        layers="A,B,C",
    ),
}

# Wall-clock budget for ONE arm, in seconds. Covers import, corpus fetch,
# calibration, training and the final hub push.
TOTAL_BUDGET_S = int(os.environ.get("TMT_FS_BUDGET_S", "3600"))
# Reserve for everything that is not training (imports, fetch, push, slack).
OVERHEAD_S = int(os.environ.get("TMT_FS_OVERHEAD_S", "600"))
TRAIN_BUDGET_S = TOTAL_BUDGET_S - OVERHEAD_S
BATCH = 1024
DATA_SEED = 42          # same ordering seed in every arm
INIT_SEED = 0           # same init in every arm
# Fetch enough corpus that a 15% re-read margin never wraps the file.
FETCH_MB = int(os.environ.get("TMT_FS_FETCH_MB", "130"))
SAVE_EVERY = 2000
# The locally staged TinyStories files cover the head of the train file; start
# past them so this arm's text is novel w.r.t. the eval ruler.
TS_OFFSET_MB = int(os.environ.get("TMT_FS_TS_OFFSET_MB", "220"))
# Toy size for the local CPU smoke test; never used in a real arm.
SMOKE_DIM = int(os.environ.get("TMT_FS_SMOKE_DIM", "64"))
SMOKE_LAYERS = int(os.environ.get("TMT_FS_SMOKE_LAYERS", "2"))


TEMPLATE = r'''#!/usr/bin/env python3
"""GENERATED by make_fs_bundle.py -- {name}: {question}

1h GPU budget. Trains FROM t=0 on a seeded init, one corpus, then pushes the
final tag (colab run releases the VM, so anything unpushed is lost).
"""
import os
import subprocess
import sys
import time
import urllib.request

# `colab run` executes the script inside a notebook cell, where __file__ does
# not exist and the repo lands in /content. Prefer whichever directory
# actually holds train_gpu.py.
HERE = (os.path.dirname(os.path.abspath(__file__))
        if "__file__" in globals() else os.getcwd())
if not os.path.isfile(os.path.join(HERE, "train_gpu.py")):
    for _cand in ("/content", os.getcwd()):
        if os.path.isfile(os.path.join(_cand, "train_gpu.py")):
            HERE = _cand
            break
sys.path.insert(0, HERE)

ARM          = "{name}"
QUESTION     = "{question}"
KIND         = "{kind}"
LAYERS       = "{layers}"
TOTAL_BUDGET_S = {total_budget_s}
TRAIN_BUDGET_S = {train_budget_s}
OVERHEAD_S   = {overhead_s}
BATCH        = {batch}
FETCH_MB     = {fetch_mb}
DATA_SEED    = {data_seed}
INIT_SEED    = {init_seed}
SAVE_EVERY   = {save_every}
TS_OFFSET_MB = {ts_offset_mb}
DATA_URL     = "{ts_url}"
HUB_REPO     = os.environ.get("TMT_HUB_REPO", "bakali1/tmt-checkpoints")
# TMT_FS_SMOKE=1 runs the whole pipeline on CPU at toy size, so the fetch ->
# calibrate -> train -> artifacts path can be proven locally in ~2 min instead
# of being discovered broken at minute 50 of a 1h Colab slot.
SMOKE = os.environ.get("TMT_FS_SMOKE", "0") == "1"
# A smoke test must NEVER publish to the real checkpoint repo: the HF cached
# login is picked up implicitly by huggingface_hub, so without this guard a
# local smoke run would upload toy checkpoints to the live lineage.
PUSH_ALLOWED = not SMOKE
DEVICE = "cpu" if SMOKE else "cuda"
DIM = {smoke_dim} if SMOKE else 512
LAYERS_N = {smoke_layers} if SMOKE else 16
EXPECT_P = {smoke_dim} * {smoke_layers} if False else 4481793

T0 = time.time()
CHECKS = []


def banner(s):
    print("\n" + "=" * 68 + f"\n{{s}}\n" + "=" * 68, flush=True)


def result(name, ok, note=""):
    CHECKS.append((name, bool(ok)))
    print(f"  [{{'PASS' if ok else 'FAIL'}}] {{name}}  {{note}}", flush=True)
    return bool(ok)


def left():
    return TOTAL_BUDGET_S - (time.time() - T0)


# ---------------- auth: a Colab secret, never an embedded credential -------
TMT_TOKEN = os.environ.get("TMT_TOKEN", "")
if not TMT_TOKEN:
    try:
        from google.colab import userdata
        TMT_TOKEN = userdata.get("TMT_TOKEN") or ""
    except Exception:
        pass
if TMT_TOKEN:
    os.environ["TMT_TOKEN"] = TMT_TOKEN
    print("[auth] TMT_TOKEN present (value not shown)", flush=True)
elif PUSH_ALLOWED:
    print("[auth] WARNING: no TMT_TOKEN; the final tag cannot be pushed and "
          "will be LOST when the VM is released", flush=True)

if not PUSH_ALLOWED:
    # Drop any ambient HF login so nothing can reach the hub by accident.
    os.environ["HF_HUB_OFFLINE"] = "1"
    os.environ.pop("TMT_TOKEN", None)
    print("[smoke] push DISABLED and HF put offline", flush=True)

banner("env")
import torch
print(f"  torch {{torch.__version__}} | cuda {{torch.cuda.is_available()}} | "
      f"{{torch.cuda.get_device_name(0) if torch.cuda.is_available() else 'CPU'}}"
      f" | mode {{'SMOKE' if SMOKE else 'REAL'}}", flush=True)
if not torch.cuda.is_available() and not SMOKE:
    print("FATAL: no CUDA device")
    sys.exit(2)

# ---------------- corpus, downloaded in-session ---------------------------
banner("corpus (in-session, never shipped from the laptop)")
os.makedirs("./fs_corpus", exist_ok=True)
data_path = None
t_fetch = time.time()

if KIND == "tinystories":
    # Range-fetch a slice STARTING PAST the locally staged region so this arm's
    # text cannot overlap the ruler's eval set.
    data_path = "./fs_corpus/arm_w.txt"
    off = TS_OFFSET_MB * 1_000_000
    want = FETCH_MB * 1_000_000
    if SMOKE and os.environ.get("TMT_FS_SMOKE_LOCAL", "0") == "1":
        # The smoke test validates the PIPELINE, not the network (the Colab
        # fetch is already proven by make_leg_bundle.py). Laptop links to HF
        # are slow enough to stall, so synthesize the bytes locally.
        import numpy as _np
        _rs = _np.random.default_rng(0)
        with open(data_path, "wb") as _f:
            _f.write((_rs.integers(97, 123, FETCH_MB * 1_000_000)
                      .astype(_np.uint8)).tobytes())
        got = os.path.getsize(data_path)
    elif not (os.path.exists(data_path)
            and os.path.getsize(data_path) >= want):
        # Retry the whole range: a single stalled read must not kill an
        # unattended hour. Partial data is discarded between attempts.
        for attempt in range(1, 4):
            try:
                req = urllib.request.Request(
                    DATA_URL,
                    headers={{"Range": f"bytes={{off}}-{{off + want - 1}}"}})
                got = 0
                with urllib.request.urlopen(req, timeout=60) as r, \
                        open(data_path + ".part", "wb") as f:
                    if r.status == 200 and not r.headers.get("Content-Range"):
                        print("  [warn] server ignored Range; capping local read",
                              flush=True)
                    while got < want:
                        chunk = r.read(min(1 << 20, want - got))
                        if not chunk:
                            break
                        f.write(chunk)
                        got += len(chunk)
                if got < want:
                    raise IOError(f"short read {{got}}/{{want}}")
                os.replace(data_path + ".part", data_path)
                break
            except Exception as e:
                print(f"  [retry {{attempt}}/3] {{type(e).__name__}}: {{e}}",
                      flush=True)
                if os.path.exists(data_path + ".part"):
                    os.remove(data_path + ".part")
                if attempt == 3:
                    print("FATAL: could not fetch the corpus slice")
                    sys.exit(2)
                time.sleep(5)
    else:
        got = os.path.getsize(data_path)
    print(f"  TinyStories @ +{{TS_OFFSET_MB}}MB: {{got/1e6:.1f}} MB in "
          f"{{time.time()-t_fetch:.0f}}s", flush=True)
else:
    # Gutenberg / FineWeb-Edu / UltraChat via the shared, already-tested
    # stager. It publishes versioned files and a `current` symlink.
    cmd = [sys.executable, os.path.join(HERE, "fetch_corpus.py"),
           "--layers", LAYERS, "--mb", str(max(FETCH_MB // 3, 40)),
           "--out", "./fs_corpus", "--seed", str(DATA_SEED)]
    print("  $ " + " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)
    import glob as _glob
    hits = _glob.glob("./fs_corpus/current/**/corpus_*", recursive=True)
    data_path = hits[0] if len(hits) == 1 else "./fs_corpus/current/**/corpus_*"

nbytes = 0
if os.path.isfile(data_path):
    nbytes = os.path.getsize(data_path)
else:
    import glob as _glob
    nbytes = sum(os.path.getsize(p) for p in
                 _glob.glob(data_path, recursive=True) if os.path.isfile(p))
result("corpus-fetched", nbytes > 0,
       f"{{nbytes/1e6:.1f}} MB for {{ARM}} in {{time.time()-t_fetch:.0f}}s")
if left() < 600:
    print("FATAL: fetch ate the budget")
    sys.exit(2)

# ---------------- calibrate: measure, then size the run -------------------
banner("calibrate (measure B/s, then derive steps for the budget)")
CAL = 24
cal_path = "./fs_cal.npz"
if os.path.exists(cal_path):
    os.remove(cal_path)
cal = subprocess.run(
    [sys.executable, os.path.join(HERE, "train_gpu.py"), cal_path, "train",
     "--from-scratch", "--seed", str(INIT_SEED),
     "--data-seed", "9999",                      # a different order: init only
     "--batch", str(BATCH), "--dim", str(DIM), "--layers", str(LAYERS_N),
     "--steps", str(CAL), "--no-save", "--no-tagged",
     "--log-every", str(CAL // 3),
     "--dataset", data_path,
     "--device", DEVICE, "--ring-credit", "full" if SMOKE else "auto"],
    cwd=HERE, env=os.environ, capture_output=True, text=True)
if cal.returncode != 0:
    print(cal.stdout[-3000:]); print(cal.stderr[-3000:])
    print("FATAL: calibration run failed")
    sys.exit(2)
rate = None
for line in cal.stdout.splitlines():
    import re
    mm = re.search(r"\| ([\d,]+) B/s \|", line)
    if mm:
        rate = float(mm.group(1).replace(",", ""))
if not rate:
    print(cal.stdout[-3000:])
    print("FATAL: could not read a rate from calibration")
    sys.exit(2)

steps_by_time = int(TRAIN_BUDGET_S * rate / BATCH)
steps_by_data = int(nbytes * 0.87 / BATCH)      # inverse of the 1.15 re-read
STEPS = max(100, min(steps_by_time, steps_by_data))
print(f"  rate {{rate:,.0f}} B/s | time allows {{steps_by_time:,}} steps | "
      f"data allows {{steps_by_data:,}} -> STEPS={{STEPS:,}} "
      f"(~{{STEPS*BATCH/1e6:.0f}} MB, {{TRAIN_BUDGET_S/60:.0f}} min)",
      flush=True)
result("steps-fit-budget", steps_by_time >= STEPS and steps_by_data >= STEPS,
       f"{{STEPS:,}} within both the time and data envelopes")

# ---------------- train from t=0 -----------------------------------------
banner(f"train {{STEPS:,}} steps from t=0 on {{ARM}}")
out = os.path.join(HERE, f"fs_{{ARM.lower()}}.npz")
if os.path.exists(out):
    os.remove(out)
cmd = [sys.executable, os.path.join(HERE, "train_gpu.py"), out, "train",
       "--from-scratch", "--seed", str(INIT_SEED),
       "--data-seed", str(DATA_SEED),
       "--batch", str(BATCH), "--dim", str(DIM), "--layers", str(LAYERS_N),
       "--steps", str(STEPS), "--save-every", str(SAVE_EVERY),
       "--device", DEVICE, "--ring-credit", "full" if SMOKE else "auto"]
if PUSH_ALLOWED:
    cmd += ["--hub-repo", HUB_REPO, "--push"]
cmd += ["--dataset", data_path]
print("  $ " + " ".join(cmd[:6]) + " ...", flush=True)
t_train = time.time()
proc = subprocess.run(cmd, cwd=HERE, env=os.environ, text=True,
                      stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
sys.stdout.write(proc.stdout[-12000:])
elapsed = time.time() - t_train
result("train-exit", proc.returncode == 0, f"rc={{proc.returncode}}")
result("within-budget", elapsed <= TOTAL_BUDGET_S + 120,
       f"{{elapsed/60:.1f}} min of {{TOTAL_BUDGET_S/60:.0f}} min")

# ---------------- verdict on the artifacts ------------------------------
banner("artifacts")
import glob as _glob
import numpy as np
tags = sorted(_glob.glob(HERE + f"/fs_{{ARM.lower()}}_t*.npz"))
result("tag-exists", len(tags) > 0, f"{{len(tags)}} tag(s)")
if tags:
    d = np.load(tags[-1])
    t_seen = int(d["t"])
    hot = len([k for k in d.files if k.startswith("tail_cols.")])
    result("trained-from-zero", t_seen > STEPS * 0.9,
           f"t={{t_seen:,}} (expected ~{{STEPS:,}})")
    # The strongest shape check is that the artifact LOADS into a fresh model
    # with the same geometry -- this also proves the checkpoint is evaluable,
    # which is the whole point of pushing it. (Counting the named tensors is
    # fragile: theta is a flat view whose composition is not the file's.)
    import gpu_port as _gp
    _ref = _gp.GpuModel(dim=DIM, layers=LAYERS_N, device="cpu")
    expect_p = int(_ref.theta.numel())
    loaded = False
    detail = ""
    try:
        loaded = bool(_ref.load(tags[-1]))
        detail = (f"params={{int(_ref.theta.numel()):,}} "
                  f"(model {{expect_p:,}}), round-trip t={{int(_ref.t):,}}")
    except Exception as e:
        detail = f"load failed: {{type(e).__name__}}: {{e}}"
    result("checkpoint-loads", loaded, detail)
    print(f"  hot dims: {{hot}} | bytes_seen: {{int(d.get('bytes_seen', 0)):,}}",
          flush=True)
    if PUSH_ALLOWED and TMT_TOKEN:
        pushed = [p for p in tags if os.path.getsize(p) > 0]
        result("push-attempted", bool(pushed),
               "final tag pushed by train_gpu --push")
    elif SMOKE:
        print("  [smoke] push intentionally skipped", flush=True)

banner("summary")
for n, ok in CHECKS:
    print(f"  {{'PASS' if ok else 'FAIL'}}  {{n}}")
failed = [n for n, ok in CHECKS if not ok]
print("\n" + ("=" * 68))
print(f"{{ARM}} ({{QUESTION}})")
print(f"  steps={{STEPS:,}}  rate={{rate:,.0f}} B/s  "
      f"train={{elapsed/60:.1f}} min  total={{(time.time()-T0)/60:.1f}} min")
print("RESULT: " + ("PASS" if not failed else f"FAIL {{failed}}"))
print("=" * 68)
'''


def build(arm, cfg):
    body = TEMPLATE.format(
        name=cfg["name"], question=cfg["question"], kind=cfg["kind"],
        layers=cfg.get("layers", ""), total_budget_s=TOTAL_BUDGET_S,
        train_budget_s=TRAIN_BUDGET_S, overhead_s=OVERHEAD_S, batch=BATCH,
        fetch_mb=FETCH_MB, data_seed=DATA_SEED, init_seed=INIT_SEED,
        save_every=SAVE_EVERY, ts_offset_mb=TS_OFFSET_MB, ts_url=TINYSTORIES,
        smoke_dim=SMOKE_DIM, smoke_layers=SMOKE_LAYERS)
    path = os.path.join(HERE, f"colab_fs_{arm}.py")
    with open(path, "w") as f:
        f.write(body)
    os.chmod(path, os.stat(path).st_mode | stat.S_IEXEC)
    return path


def main():
    arms = sys.argv[1:] or list(ARMS)
    for a in arms:
        if a not in ARMS:
            sys.exit(f"unknown arm {a!r}; choose from {list(ARMS)}")
        p = build(a, ARMS[a])
        q = ARMS[a]["question"]
        print(f"wrote {os.path.relpath(p, HERE)}  ({ARMS[a]['name']}: {q})")
    print(f"\n1h budget each; run one at a time:\n"
          f"  colab run --gpu T4 --timeout {TOTAL_BUDGET_S + 600} "
          f"colab_fs_{arms[0]}.py")


if __name__ == "__main__":
    main()
