def local_token():
    """The HF login cached on this laptop, for the generated bundle.

    `colab run` forwards neither env vars nor logins, and the Colab secret was
    not present on the session that pushed the first arms, so the token has to
    travel inside the script. The generated colab_fs_*.py files are gitignored
    and must never be committed.
    """
    try:
        import huggingface_hub as _h
        return _h.get_token() or ""
    except Exception:
        return ""


def build(arm, cfg):
    import base64 as _b64mod
    import gzip as _gz
    payload = {}
    for name in MODULES:
        with open(os.path.join(HERE, name), "rb") as f:
            payload[name] = _b64mod.b64encode(_gz.compress(f.read(), 9)).decode()
    # Format FIRST, then inject the payload: the base64 blob is full of braces
    # and would be chewed up by str.format if it were substituted before.
    body = TEMPLATE.format(
        name=cfg["name"], question=cfg["question"], kind=cfg["kind"],
        layers=cfg.get("layers", ""), total_budget_s=TOTAL_BUDGET_S,
        train_budget_s=TRAIN_BUDGET_S, overhead_s=OVERHEAD_S, batch=BATCH,
        fetch_mb=FETCH_MB, data_seed=DATA_SEED, init_seed=INIT_SEED,
        save_every=SAVE_EVERY, ts_offset_mb=TS_OFFSET_MB, ts_url=TINYSTORIES,
        smoke_dim=SMOKE_DIM, smoke_layers=SMOKE_LAYERS,
        token=local_token(), pinned=PINNED_STEPS)
    body = body.replace(
        "__PAYLOAD__",
        "{" + ", ".join(f'"{k}": "{v}"' for k, v in payload.items()) + "}")
    path = os.path.join(HERE, f"colab_fs_{arm}.py")
    with open(path, "w") as f:
        f.write(body)
    os.chmod(path, os.stat(path).st_mode | stat.S_IEXEC)
    return path


def main():
    arms = sys.argv[1:] or list(ARMS)
    for a in arms:
        if a not in ARMS:
            sys.exit(f"unknown arm {a!r}; choose from {list(ARMS)}")
        p = build(a, ARMS[a])
        q = ARMS[a]["question"]
        print(f"wrote {os.path.relpath(p, HERE)}  ({ARMS[a]['name']}: {q})")
    print(f"\n1h budget each; run one at a time:\n"
          f"  colab run --gpu T4 --timeout {TOTAL_BUDGET_S + 600} "
          f"colab_fs_{arms[0]}.py")


if __name__ == "__main__":
    main()
