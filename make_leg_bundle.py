#!/usr/bin/env python3
"""make_leg_bundle.py — generate the self-contained Colab LIVE-CHECKPOINT leg.

Emits `colab_leg.py`: a single script that rents a T4, pulls the real
`tmt.npz` (t=64,747) from the HF hub, pulls a 64 MB slice of the TinyStories
train file in-session, trains 30k steps at B=1024 with a tagged save every
5k, and prints a PASS/FAIL verdict for every piece of infrastructure the leg
touched.

    .venv/bin/python make_leg_bundle.py                    # writes colab_leg.py
    TMT_HUB_URL=bakali1/tmt-checkpoints TMT_TOKEN=... \
      colab run --gpu T4 --timeout 3600 colab_leg.py

Why the checkpoint comes from the hub: `colab run` executes a single script on
a fresh VM, so a 173 MB npz cannot ride along; `colab upload` needs a
babysat session. The hub path is also the thing we want proven, so the leg
tests load-from-hub instead of working around it.

Local rehearsal (no GPU, a few steps, real checkpoint, real corpus):

    TMT_DEVICE=cpu TMT_STEPS=20 TMT_SAVE_EVERY=10 TMT_DATA=data/alice_in_wonderland.txt \
      TMT_CKPT=tmt.npz .venv/bin/python colab_leg.py
"""
import base64
import gzip
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MODULES = ["gpu_port.py", "train_gpu.py", "numpy_port.py", "tail_credit.py",
           "checkpoint_hub.py"]

DRIVER = r'''#!/usr/bin/env python3
"""Colab LIVE-CHECKPOINT 30k-step leg — generated by make_leg_bundle.py.

This is an INTEGRATION TEST of the infrastructure, not a training run: 30k
steps x 1024 B = 30.7 MB is ~7% of the corpus, so the loss is expected to
barely move. Every stage prints a [RESULT] line and the script ends with one
OVERALL verdict. Tune with env vars (see the top of make_leg_bundle.py).
"""
import base64
import glob, gzip, os, sys, time, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__)) if "__file__" in globals() else os.getcwd()
if not os.path.isdir(HERE):
    HERE = "/content" if os.path.isdir("/content") else os.getcwd()
PAYLOAD = __PAYLOAD__

# `colab run` executes this file on a fresh VM and does NOT inherit the
# laptop's environment, so the HF token for the private checkpoint repo is
# embedded at generation time. This makes the generated file SECRET: it is
# gitignored, and keep it out of any shared repo.
TMT_TOKEN = __TOKEN__
if TMT_TOKEN:
    os.environ["TMT_TOKEN"] = TMT_TOKEN
    print(f"[auth] embedded HF token ({TMT_TOKEN[:7]}...{TMT_TOKEN[-4:]})",
          flush=True)

for name, b64 in PAYLOAD.items():
    with open(os.path.join(HERE, name), "wb") as f:
        f.write(gzip.decompress(base64.b64decode(b64)))
sys.path.insert(0, HERE)

import numpy as np
import torch
import gpu_port
import train_gpu as tg
import checkpoint_hub as hub

# ----------------------------- configuration ------------------------------
STEPS = int(os.environ.get("TMT_STEPS", "30000"))
BATCH = int(os.environ.get("TMT_BATCH", "1024"))
SAVE_EVERY = int(os.environ.get("TMT_SAVE_EVERY", "5000"))
KEEP_K = int(os.environ.get("TMT_KEEP_K", "7"))
EXPECT_T = int(os.environ.get("TMT_EXPECT_T", "64747"))
EXPECT_RING_K = int(os.environ.get("TMT_EXPECT_RING_K", "18"))
EXPECT_HOT = int(os.environ.get("TMT_EXPECT_HOT", "57"))
CKPT = os.environ.get("TMT_CKPT", "tmt.npz")
DATA = os.environ.get("TMT_DATA", "")
DATA_URL = os.environ.get(
    "TMT_DATA_URL",
    "https://huggingface.co/datasets/roneneldan/TinyStories/resolve/main/"
    "TinyStories-train.txt")
DATA_MB = int(os.environ.get("TMT_DATA_MB", "64"))
DEVICE = os.environ.get("TMT_DEVICE") or ("cuda" if torch.cuda.is_available() else "cpu")
# Throughput tripwire: the old tail-sync bug showed up as ~2.6k B/s.
MIN_BPS = float(os.environ.get("TMT_MIN_BPS",
                               "25000" if DEVICE == "cuda" else "0"))
HUB_REPO = os.environ.get("TMT_HUB_REPO") or os.environ.get("TMT_HUB_URL")
CKPT_URL = os.environ.get("TMT_CKPT_URL", "")
FAILS = []


def result(name, ok, detail=""):
    print(f"[RESULT] {name}: {'PASS' if ok else 'FAIL'} {detail}", flush=True)
    if not ok:
        FAILS.append(name)


def banner(s):
    print(f"\n===== {s} =====", flush=True)


# ---------------- A: environment ----------------
banner("A: environment")
print(f"  torch {torch.__version__} device={DEVICE}", flush=True)
if DEVICE == "cuda":
    print(f"  gpu {torch.cuda.get_device_name(0)} "
          f"allow_tf32={torch.backends.cuda.matmul.allow_tf32}", flush=True)
result("env-cuda", DEVICE == "cuda" or os.environ.get("TMT_ALLOW_CPU") == "1",
       f"device={DEVICE}")
result("tf32-off", not (DEVICE == "cuda"
                        and torch.backends.cuda.matmul.allow_tf32),
       "fp32 only; TF32 would break the parity contract")

# ---------------- B: the live checkpoint ----------------
banner("B: live checkpoint (hub -> load)")
src = None
if os.path.exists(CKPT) and os.path.getsize(CKPT) > 0:
    src = f"local file {CKPT}"
elif HUB_REPO:
    try:
        t = hub.pull(CKPT, repo_id=HUB_REPO)
        src = f"hub {HUB_REPO}" if t is not None else None
    except SystemExit as e:
        print(f"  hub pull failed: {e}", flush=True)
elif CKPT_URL:
    urllib.request.urlretrieve(CKPT_URL, CKPT)
    src = f"url {CKPT_URL}"
result("ckpt-source", src is not None,
       src or (f"none: no {CKPT}, no TMT_HUB_URL, no TMT_CKPT_URL — push the "
               "checkpoint once with: python checkpoint_hub.py push "
               "tmt_t064747.npz"))
if src is None:
    print("[RESULT] OVERALL = FAIL (no checkpoint)"); sys.exit(1)
print(f"  source: {src}  ({os.path.getsize(CKPT)/1e6:.0f} MB)", flush=True)

probe = gpu_port.GpuModel(device="cpu")
probe.new_states(1)
probe.load(CKPT)                       # CPU: cheap, no VRAM touched
t0_ck = probe.t
k_ck = probe.ring_k
hot_ck = sum(probe.tail.nhot(i) for i in range(probe.layercount)) if probe.tail else 0
print(f"  t={t0_ck} ring_k={k_ck} hot_dims={hot_ck} "
      f"bytes_seen={probe.bytes_seen:,}", flush=True)
result("ckpt-t", t0_ck == EXPECT_T, f"t={t0_ck} expected {EXPECT_T}")
result("ckpt-ring-k", k_ck == EXPECT_RING_K, f"K={k_ck} expected {EXPECT_RING_K}")
result("ckpt-hot", abs(hot_ck - EXPECT_HOT) <= 5, f"{hot_ck} hot (expect ~{EXPECT_HOT})")
del probe

# ---------------- C: corpus, in-session ----------------
banner("C: corpus (downloaded in-session)")
need = int(STEPS * BATCH * 1.15)
data_path = DATA
if data_path and os.path.exists(data_path):
    print(f"  using local {data_path}", flush=True)
else:
    data_path = "tinystories_leg.txt"
    if not os.path.exists(data_path) or os.path.getsize(data_path) < need:
        # Range request: the full train file is 1.9 GB; 64 MB is plenty for a
        # 30k-step leg and keeps the session short.
        want = max(DATA_MB * 1_000_000, need)
        req = urllib.request.Request(DATA_URL, headers={"Range": f"bytes=0-{want}"})
        t_fetch = time.time()
        with urllib.request.urlopen(req, timeout=120) as r, \
                open(data_path + ".part", "wb") as f:
            while True:
                chunk = r.read(1 << 20)
                if not chunk:
                    break
                f.write(chunk)
        os.replace(data_path + ".part", data_path)
        print(f"  fetched {os.path.getsize(data_path)/1e6:.1f} MB from "
              f"{DATA_URL.split('/')[-1]} in {time.time()-t_fetch:.0f}s",
              flush=True)
size = os.path.getsize(data_path)
result("corpus-size", size >= need, f"{size/1e6:.1f} MB >= {need/1e6:.1f} MB needed")

# ---------------- D: train ----------------
banner("D: train 30k steps (integration, not a quality run)")
# Wrap step_batch to observe: the training math is untouched (we call through).
orig_step = gpu_port.GpuModel.step_batch
S = {"n": 0, "bytes": 0, "nonfinite": 0, "loss": [], "last": float("nan"),
      "t0": time.time()}


def watched(self, c, n, e):
    loss = orig_step(self, c, n, e)
    S["n"] += 1
    S["bytes"] += int(c.numel())
    S["last"] = float(loss)
    if loss != loss or loss in (float("inf"), float("-inf")):
        S["nonfinite"] += 1
    if S["n"] % 2000 == 0:
        S["loss"].append((int(self.t), float(loss)))
        el = time.time() - S["t0"]
        print(f"  t={self.t} loss={loss:.4f} | {S['bytes']/el:,.0f} B/s "
              f"(step-time {(S['n']/el):.1f} steps/s)", flush=True)
    return loss


gpu_port.GpuModel.step_batch = watched

tr = tg.Trainer(path=CKPT, batch=BATCH, save_every=SAVE_EVERY, keep_k=KEEP_K,
                max_steps=STEPS, device=DEVICE, dim=512, layers=16, lr=5e-4)
start_t = None
wall0 = time.time()
tr.train(True, data_path, hub_repo=None)      # no hub push in this leg
wall = time.time() - wall0
start_t = tr.start_t
end_t = tr.model.t
bps = S["bytes"] / max(1e-9, time.time() - S["t0"])
print(f"\n  steps run {S['n']} | wall {wall/60:.1f} min | "
      f"step-time {bps:,.0f} B/s | t {start_t} -> {end_t}", flush=True)
result("steps-executed", S["n"] == STEPS, f"{S['n']} of {STEPS}")
result("t-advanced", end_t == start_t + STEPS, f"{start_t} -> {end_t}")
result("no-nan", S["nonfinite"] == 0, f"{S['nonfinite']} non-finite losses")
result("throughput", bps >= MIN_BPS, f"{bps:,.0f} B/s (floor {MIN_BPS:,.0f})")
if S["loss"]:
    print("  loss trace: " + " ".join(f"{t}:{l:.3f}" for t, l in S["loss"]),
          flush=True)

# ---------------- E: saves ----------------
banner("E: tagged saves")
tags = sorted(glob.glob(f"{os.path.splitext(os.path.basename(CKPT))[0]}_t*.npz"))
print("  " + ", ".join(os.path.basename(t) for t in tags), flush=True)
# Periodic saves fire on ABSOLUTE t % save_every, so how many land inside the
# leg depends on start_t alignment (here 64747). Assert the shape, not a count.
result("save-tags", 1 <= len(tags) <= KEEP_K,
       f"{len(tags)} tag(s) in [1, keep_k={KEEP_K}]")
result("save-keep-k", len(tags) <= KEEP_K, f"keep_k={KEEP_K}")
newest = max(tags, key=os.path.getmtime) if tags else None
result("rolling-links-newest",
       newest is not None and os.path.exists(CKPT)
       and os.path.samefile(CKPT, newest),
       f"rolling -> {os.path.basename(newest) if newest else 'none'}")
if tags:
    lt = gpu_port.GpuModel(device="cpu"); lt.new_states(1); lt.load(newest)
    result("saved-loads", lt.t == end_t, f"saved t={lt.t} == live t={end_t}")
    steps_in = None
    import numpy as _np
    tag_ts = sorted(int(_np.load(t)["t"]) for t in tags)
    result("tags-in-range", all(start_t < tt <= end_t for tt in tag_ts)
           and tag_ts == sorted(set(tag_ts)),
           f"tag steps {tag_ts} within ({start_t}, {end_t}]")

# ---------------- F: sanity band ----------------
banner("F: loss sanity (smoke band, not a quality gate)")
final = S["last"]
lo, hi = float(os.environ.get("TMT_CE_LO", "0.5")), float(os.environ.get("TMT_CE_HI", "2.5"))
result("loss-finite", final == final and abs(final) != float("inf"),
       f"final loss {final:.4f}")
result("loss-band", lo <= final <= hi,
       f"{final:.4f} in [{lo}, {hi}] (baseline in-domain CE 1.17)")

banner("OVERALL")
print(f"[RESULT] OVERALL = {'FAIL ' + str(FAILS) if FAILS else 'PASS'}", flush=True)
print(f"\nNext: colab download the newest tag, then judge it on CPU:\n"
      f"  .venv/bin/python eval.py {os.path.basename(newest) if newest else CKPT}\n"
      f"Compare against the clean-baseline row in RESULTS.md "
      f"(in-domain 1.1741 +/- 0.0415). A 30k-step infra leg should NOT move it "
      f"much; a large move in either direction is the signal to investigate.",
      flush=True)
sys.exit(1 if FAILS else 0)
'''


def _token():
    """HF token for embedding: env first, then the cached CLI login."""
    t = os.environ.get("TMT_TOKEN")
    if t:
        return t.strip()
    for p in (os.path.expanduser("~/.cache/huggingface/token"),
              os.path.expanduser("~/.huggingface/token")):
        try:
            with open(p) as f:
                return f.read().strip()
        except OSError:
            continue
    return ""


def main():
    payload = {}
    for name in MODULES:
        with open(os.path.join(HERE, name), "rb") as f:
            payload[name] = base64.b64encode(gzip.compress(f.read(), 9)).decode()
    out = DRIVER.replace("__PAYLOAD__", "{" + ", ".join(
        f"{k!r}: {v!r}" for k, v in payload.items()) + "}")
    out = out.replace("__TOKEN__", repr(_token()))
    path = os.path.join(HERE, "colab_leg.py")
    with open(path, "w") as f:
        f.write(out)
    print(f"wrote {path} ({os.path.getsize(path)/1024:.0f} KB)"
          f"{'  [CONTAINS AN HF TOKEN - keep it local]' if _token() else ''}")


if __name__ == "__main__":
    main()
