#!/usr/bin/env python3
"""make_bench_bundle.py — self-contained Colab run of the Phase-0 variant board.

Emits `colab_bench.py`: rents a T4, pulls the live checkpoint from the HF hub,
then benchmarks every optimization candidate (plus a CUDA profile and an
isolated atomic micro-benchmark) in ONE session, so the whole board costs
~5 minutes instead of one 25-minute leg per idea.

    .venv/bin/python make_bench_bundle.py
    colab run --gpu T4 --timeout 1800 colab_bench.py

Everything `colab run` needs is embedded (token, repo id), because it forwards
no environment variables and no HF login.
"""
import base64
import gzip
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # repo root
OUT = os.path.dirname(os.path.abspath(__file__))                   # bundles/
MODULES = ["gpu_port.py", "train_gpu.py", "numpy_port.py", "tail_credit.py",
           "checkpoint_hub.py"]

DRIVER = r'''#!/usr/bin/env python3
"""Colab Phase-0 optimization board — generated by make_bench_bundle.py."""
import base64, gzip, os, sys, time, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__)) if "__file__" in globals() else os.getcwd()
if not os.path.isdir(HERE):
    HERE = "/content" if os.path.isdir("/content") else os.getcwd()
PAYLOAD = __PAYLOAD__

for name, b64 in PAYLOAD.items():
    with open(os.path.join(HERE, name), "wb") as f:
        f.write(gzip.decompress(base64.b64decode(b64)))
sys.path.insert(0, HERE)

TMT_TOKEN = __TOKEN__
if TMT_TOKEN:
    os.environ["TMT_TOKEN"] = TMT_TOKEN
HUB_REPO = os.environ.get("TMT_HUB_REPO") or os.environ.get("TMT_HUB_URL") or __REPO__

import numpy as np
import torch
import gpu_port
import checkpoint_hub as hub
import bench_variants as bv

B = int(os.environ.get("TMT_B_BENCH", "1024"))
# 200 timed steps, not 12: at 12 steps the run-to-run spread was +-3-4%, which
# is the same size as the effects being tested. 200 steps amortizes allocator
# and clock state, so sub-5% differences become readable.
STEPS = int(os.environ.get("TMT_BENCH_STEPS", "200"))
CKPT = "tmt_bench.npz"
VARIANTS = os.environ.get("TMT_VARIANTS", bv.DEFAULT_VARIANTS)
FAILS = []


def result(name, ok, detail=""):
    print(f"[RESULT] {name}: {'PASS' if ok else 'FAIL'} {detail}", flush=True)
    if not ok:
        FAILS.append(name)


print(f"torch {torch.__version__} cuda={torch.cuda.is_available()} "
      f"triton={'yes' if gpu_port.triton is not None else 'no'}", flush=True)
if not torch.cuda.is_available():
    print("[RESULT] OVERALL = FAIL (no CUDA)"); sys.exit(1)
print(f"gpu {torch.cuda.get_device_name(0)} "
      f"allow_tf32={torch.backends.cuda.matmul.allow_tf32}", flush=True)

# ---- live checkpoint (hub, digest-verified) ----
if not (os.path.exists(CKPT) and os.path.getsize(CKPT) > 0):
    t = hub.pull(CKPT, repo_id=HUB_REPO)
    result("ckpt-pulled", t is not None, f"t={t} from {HUB_REPO}")
    if t is None:
        print("[RESULT] OVERALL = FAIL (no checkpoint)"); sys.exit(1)

# ---- the board ----
t0 = time.time()
sys.argv = ["bench_variants.py", CKPT, "--B", str(B), "--steps", str(STEPS),
            "--device", "cuda", "--variants", VARIANTS, "--data", "text",
            "--rebase-check", "full,auto", "--profile", "--profile-steps", "3",
            "--atomic-microbench"]
rc = 0
try:
    rc = bv.main() or 0
except SystemExit as e:
    rc = int(e.code or 0)
except Exception as e:
    import traceback; traceback.print_exc()
    result("board-ran", False, f"{type(e).__name__}: {e}")
print(f"\n[board] finished rc={rc} in {(time.time()-t0)/60:.1f} min", flush=True)

print("\n[RESULT] OVERALL = " + ("PASS" if not FAILS else f"FAIL {FAILS}"),
      flush=True)
sys.exit(1 if FAILS else 0)
'''


def _token():
    t = os.environ.get("TMT_TOKEN")
    if t:
        return t.strip()
    for p in (os.path.expanduser("~/.cache/huggingface/token"),
              os.path.expanduser("~/.huggingface/token")):
        try:
            with open(p) as f:
                return f.read().strip()
        except OSError:
            continue
    return ""


def _repo():
    raw = (os.environ.get("TMT_HUB_REPO") or os.environ.get("TMT_HUB_URL")
           or "").strip().rstrip("/")
    if not raw:
        return "bakali1/tmt-checkpoints"
    for prefix in ("https://huggingface.co/", "http://huggingface.co/"):
        if raw.startswith(prefix):
            raw = raw[len(prefix):]
    parts = [p for p in raw.split("/") if p and p not in ("tree", "main",
                                                          "datasets")]
    return "/".join(parts[:2]) if len(parts) >= 2 else raw


def main():
    payload = {}
    # bench_variants.py lives in tools/, but it must be written FLAT into the
    # payload so its `import gpu_port` resolves after unpacking on Colab.
    # "srcpath" is read from the repo, the basename is what lands in the VM.
    for name in MODULES + ["tools/bench_variants.py"]:
        with open(os.path.join(HERE, name), "rb") as f:
            payload[os.path.basename(name)] = base64.b64encode(
                gzip.compress(f.read(), 9)).decode()
    out = DRIVER.replace("__PAYLOAD__", "{" + ", ".join(
        f"{k!r}: {v!r}" for k, v in payload.items()) + "}")
    out = out.replace("__TOKEN__", repr(_token()))
    out = out.replace("__REPO__", repr(_repo()))
    path = os.path.join(OUT, "colab_bench.py")
    with open(path, "w") as f:
        f.write(out)
    print(f"wrote {path} ({os.path.getsize(path)/1024:.0f} KB)"
          f"{'  [CONTAINS AN HF TOKEN - keep it local]' if _token() else ''}")


if __name__ == "__main__":
    main()
