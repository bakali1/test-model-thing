#!/usr/bin/env python3
"""make_leg_bundle.py — generate the self-contained Colab LIVE-CHECKPOINT leg.

Emits `colab_leg.py`: a single script that rents a T4, pulls the real
`tmt.npz` (t=64,747) from the HF hub, pulls a bounded TinyStories slice
in-session, trains 10k steps at B=1024 with a tagged save every 5k, and
prints a PASS/FAIL verdict for every piece of infrastructure the leg touched.

    .venv/bin/python make_leg_bundle.py                    # writes colab_leg.py
    colab run --gpu T4 --timeout 3600 colab_leg.py

For a private Hub repository, configure a Colab secret named `TMT_TOKEN`.
The generated bundle never embeds credentials and never reads the local HF
login cache. `colab run` does not forward laptop environment variables, so a
secret is the supported authentication path. Public repositories need no
token.

Local rehearsal (no GPU, a few steps, real checkpoint, real corpus):

    TMT_DEVICE=cpu TMT_STEPS=20 TMT_SAVE_EVERY=10 TMT_DATA=data/alice_in_wonderland.txt \
      TMT_CKPT=tmt.npz .venv/bin/python colab_leg.py
"""
