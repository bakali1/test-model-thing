MIN_BPS = float(os.environ.get("TMT_MIN_BPS",
                               "18000" if DEVICE == "cuda" else "0"))
PUSH = os.environ.get("TMT_PUSH", "1") == "1"
# `colab run` does not forward ANY environment variable from the laptop, so
# the hub repo id is embedded at generation time too (an env var still wins if
# the runner ever does pass one).
HUB_REPO = (os.environ.get("TMT_HUB_REPO") or os.environ.get("TMT_HUB_URL")
            or __REPO__)
CKPT_URL = os.environ.get("TMT_CKPT_URL", "")
FAILS = []


def result(name, ok, detail=""):
    print(f"[RESULT] {name}: {'PASS' if ok else 'FAIL'} {detail}", flush=True)
    if not ok:
        FAILS.append(name)


def banner(s):
    print(f"\n===== {s} =====", flush=True)


# ---------------- A: environment ----------------
banner("A: environment")
print(f"  torch {torch.__version__} device={DEVICE}", flush=True)
if DEVICE == "cuda":
    print(f"  gpu {torch.cuda.get_device_name(0)} "
          f"allow_tf32={torch.backends.cuda.matmul.allow_tf32}", flush=True)
result("env-cuda", DEVICE == "cuda" or os.environ.get("TMT_ALLOW_CPU") == "1",
       f"device={DEVICE}")
result("tf32-off", not (DEVICE == "cuda"
                        and torch.backends.cuda.matmul.allow_tf32),
       "fp32 only; TF32 would break the parity contract")

# ---------------- B: the live checkpoint ----------------
banner("B: live checkpoint (hub -> load)")
src = None
if HUB_REPO:
    try:
        t = hub.pull(CKPT, repo_id=HUB_REPO, expect_n=4481793,
                     require_digest=True)
        if t is not None or (os.path.exists(CKPT) and os.path.getsize(CKPT) > 0):
            src = f"hub {HUB_REPO}" if t is not None else f"local file {CKPT}"
    except SystemExit as e:
        print(f"  hub pull failed: {e}", flush=True)
if src is None and os.path.exists(CKPT) and os.path.getsize(CKPT) > 0:
    src = f"local file {CKPT}"
if src is None and CKPT_URL:
    urllib.request.urlretrieve(CKPT_URL, CKPT)
    src = f"url {CKPT_URL}"
result("ckpt-source", src is not None,
       src or (f"none: no {CKPT}, no TMT_HUB_URL, no TMT_CKPT_URL — push the "
               "checkpoint once with: python checkpoint_hub.py push "
               "tmt_t064747.npz"))
if src is None:
    print("[RESULT] OVERALL = FAIL (no checkpoint)"); sys.exit(1)
print(f"  source: {src}  ({os.path.getsize(CKPT)/1e6:.0f} MB)", flush=True)

probe = gpu_port.GpuModel(device="cpu")
probe.new_states(1)
probe.load(CKPT)                       # CPU: cheap, no VRAM touched
t0_ck = probe.t
k_ck = probe.ring_k
hot_ck = sum(probe.tail.nhot(i) for i in range(probe.layercount)) if probe.tail else 0
print(f"  t={t0_ck} ring_k={k_ck} hot_dims={hot_ck} "
      f"bytes_seen={probe.bytes_seen:,}", flush=True)
result("ckpt-t", t0_ck == EXPECT_T, f"t={t0_ck} expected {EXPECT_T}")
result("ckpt-ring-k", k_ck == EXPECT_RING_K, f"K={k_ck} expected {EXPECT_RING_K}")
result("ckpt-hot", abs(hot_ck - EXPECT_HOT) <= 5, f"{hot_ck} hot (expect ~{EXPECT_HOT})")
del probe

# ---------------- C: corpus, in-session ----------------
banner("C: corpus (downloaded in-session)")
need = int(STEPS * BATCH * 1.15)
data_path = DATA
if data_path and os.path.exists(data_path):
    print(f"  using local {data_path}", flush=True)
else:
    data_path = "tinystories_leg.txt"
    if not os.path.exists(data_path) or os.path.getsize(data_path) < need:
        # Range request: the full train file is 1.9 GB; 64 MB is plenty for a
        # 10k-step leg. Enforce the local byte cap even if the server ignores
        # Range and returns 200 with the full file.
        want = max(DATA_MB * 1_000_000, need)
        req = urllib.request.Request(DATA_URL, headers={"Range": f"bytes=0-{want - 1}"})
        t_fetch = time.time()
        downloaded = 0
        with urllib.request.urlopen(req, timeout=120) as r, \
                open(data_path + ".part", "wb") as f:
            status = getattr(r, "status", r.getcode())
            if status == 200 and not r.headers.get("Content-Range"):
                print("  [warn] source ignored Range; capping local read", flush=True)
            while downloaded < want:
                chunk = r.read(min(1 << 20, want - downloaded))
                if not chunk:
                    break
                f.write(chunk)
                downloaded += len(chunk)
        os.replace(data_path + ".part", data_path)
        print(f"  fetched {os.path.getsize(data_path)/1e6:.1f} MB from "
              f"{DATA_URL.split('/')[-1]} in {time.time()-t_fetch:.0f}s",
              flush=True)
size = os.path.getsize(data_path)
result("corpus-size", size >= need, f"{size/1e6:.1f} MB >= {need/1e6:.1f} MB needed")

# ---------------- D: train ----------------
banner("D: train 10k steps (integration, not a quality run)")
# Wrap step_batch to observe: the training math is untouched (we call through).
orig_step = gpu_port.GpuModel.step_batch
S = {"n": 0, "bytes": 0, "nonfinite": 0, "loss": [], "last": float("nan"),
      "t0": time.time()}


def watched(self, c, n, e):
    loss = orig_step(self, c, n, e)
    S["n"] += 1
    S["bytes"] += int(c.numel())
    S["last"] = float(loss)
    if loss != loss or loss in (float("inf"), float("-inf")):
        S["nonfinite"] += 1
    if S["n"] % 2000 == 0:
        S["loss"].append((int(self.t), float(loss)))
        el = time.time() - S["t0"]
        if "w0" not in S:                       # window start for steady state
            S["w0"] = (S["n"], S["bytes"], el)
        print(f"  t={self.t} loss={loss:.4f} | {S['bytes']/el:,.0f} B/s "
              f"(step-time {(S['n']/el):.1f} steps/s)", flush=True)
    return loss


# Install the watcher AFTER the diagnostics: they call step_batch too, and
# counting their steps made a 30k leg report 30,408.
gpu_port.GpuModel.step_batch = watched

# --- EOS diagnostic: is the real-text slowdown the end-of-stream path? The
# synthetic bench used ends=0; real text ends ~2% of streams every step. Same
# model, same bytes, only the end-flag density differs.
def _bench(nsteps, eos_p):
    m = gpu_port.GpuModel(device=DEVICE, dim=512, layers=16, lr=5e-4)
    m.new_states(BATCH)
    m.load(CKPT)
    c = torch.randint(1, 250, (BATCH,), device=DEVICE)
    nn_ = torch.randint(1, 250, (BATCH,), device=DEVICE)
    if eos_p > 0:
        g = torch.Generator(device="cpu").manual_seed(3)
        mask = (torch.rand(BATCH, generator=g) < eos_p).float()
        e = mask.to(DEVICE)
    else:
        e = torch.zeros(BATCH, dtype=torch.float32, device=DEVICE)
    for _ in range(4):
        m.step_batch(c, nn_, e)
    if DEVICE == "cuda":
        torch.cuda.synchronize()
    t0 = time.time()
    for _ in range(nsteps):
        m.step_batch(c, nn_, e)
    if DEVICE == "cuda":
        torch.cuda.synchronize()
    return BATCH * nsteps / (time.time() - t0)


if DEVICE == "cuda" and os.environ.get("TMT_EOS_DIAG", "1") == "1":
    r0 = _bench(200, 0.0)
    r2 = _bench(200, 0.02)
    # Tail cost: the SAME bench with the tail disabled (GpuModel reads
    # TMT_TAIL at construction). Tells us what fraction of the step the
    # hot-dim credit path costs, which grows with the hot set.
    os.environ["TMT_TAIL"] = "0"
    r_notail = _bench(200, 0.0)
    os.environ["TMT_TAIL"] = "1"
    print(f"  [diag] synthetic, ends=0:    {r0:,.0f} B/s", flush=True)
    print(f"  [diag] synthetic, ends=2%:  {r2:,.0f} B/s "
          f"({100*(1-r2/r0):.1f}% cost)", flush=True)
    print(f"  [diag] tail disabled:       {r_notail:,.0f} B/s "
          f"(tail costs {100*(1-r0/r_notail):.1f}%)", flush=True)
    # The old tail-sync bug is 2,655 B/s; anything near 20k is healthy. The
    # earlier 32.4 kB/s figure came from a DIFFERENT (synthetic) checkpoint.
    result("diag-bench-baseline", r0 > 18000, f"ends=0 {r0:,.0f} B/s")
    result("diag-eos-cost", r2 > r0 * 0.9,
           f"2% ends costs {100*(1-r2/r0):.1f}% ({r2:,.0f} B/s)")
    result("diag-tail-cost", r_notail > r0 * 0.9,
           f"tail costs {100*(1-r0/r_notail):.1f}% of the step")

