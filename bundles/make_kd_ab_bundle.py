#!/usr/bin/env python3
"""make_kd_ab_bundle.py — the distillation A/B on a T4, at the frozen B=1024.

    .venv/bin/python bundles/make_kd_ab_bundle.py
    colab run --gpu T4 --timeout 5400 bundles/colab_kd_ab.py
    colab download <session> ./ckpt_armKD_t015000.npz

THREE arms, not two, and that is the whole point of this bundle:

  A  CE only                          --distill-alpha 0
  C  half-CE control, zero target    --distill-alpha 0.5 --distill-null-target
  B  MI-KD, corrected target         --distill-alpha 0.5 --distill-dir ...

With alpha=0.5 the CE weight becomes (1-alpha) at EVERY position while the KD
term fires only where a target exists. A "KD arm" is therefore half-strength CE
everywhere plus a soft label on a subset, and a KD-vs-CE comparison does not
isolate distillation. Arm C is the control that does; it was added 2026-10-04
after the 2026-10-03 closure was found to rest on an uninterpretable A/B.

The `ce` column is comparable across all three (same CE term, same bytes). The
total `loss` is NOT, by construction.

Writes the final checkpoint of every arm so they can be pushed to the hub with
`checkpoint_hub.push`, which is the only sanctioned path (it validates that the
internal t matches the filename and uploads a .sha256 sidecar beside it).

No credentials are embedded and nothing is pushed from Colab: the teacher and
the corpus are public, and the hub push happens locally.
"""
