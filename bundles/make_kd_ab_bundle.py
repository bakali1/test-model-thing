def cpu_gate3(steps=120):
    B, dim, layers = 16, 32, 3
    rng = np_.np.random.default_rng(3)
    cs = torch.from_numpy(rng.integers(1, 250, (steps, B)).astype(np.int64))
    ns = torch.from_numpy(rng.integers(1, 250, (steps, B)).astype(np.int64))
    es = torch.zeros((steps, B), dtype=torch.float32)

    def go(alpha, provider):
        m = gpu_port.GpuModel(dim=dim, layers=layers, device="cpu",
                              ring_credit="full", seed=7, distill_alpha=alpha)
        m.new_states(B)
        if provider:
            m.set_target_fn(lambda s: torch.eye(256, B)[s % 256])
        for t in range(steps):
            m.step_batch(cs[t], ns[t], es[t])
        return m.theta.detach().clone()

    return float((go(0.0, True) - go(0.0, False)).abs().max())


