#!/usr/bin/env python3
"""make_lr_roles_bundle.py — generate the Colab role-specific-LR FACTORIAL.

Emits `colab_lr_roles.py`: one self-contained script that rents a T4, pulls the
incumbent checkpoint once, and then runs SEVERAL arms that differ ONLY in the
learning rate applied to the 16 per-layer `.decay` slices (512 coords each =
8,192 = 0.183% of the 4,481,793 parameters). Every arm starts from the SAME
checkpoint bytes and the SAME data seed, so the arms are matched on every axis
except the one under test.

    .venv/bin/python bundles/make_lr_roles_bundle.py
    colab run --gpu T4 --timeout 7200 bundles/colab_lr_roles.py

Why Colab and not the local box: a T4 sustains ~22 kB/s against the MX150's
4.2 kB/s on a mature ring_k=18 checkpoint, so one 30-minute slot buys ~5x the
steps per arm here.

Why the arms are resumable (this is the whole point of doing this axis first):
`--lr-decay` changes the learning RATE, not the optimizer STATE format, so every
arm branches off the incumbent with AdamW's m/v carried over. An AdamW->SGD arm
could not do that -- it changes what a checkpoint contains -- which is why the
SGD row is a separate, more expensive experiment.

Auth: for a private Hub repo supply a Colab secret named `TMT_TOKEN`. The
generated bundle never embeds credentials.

Local rehearsal (CPU, a few steps, no hub):
    TMT_DEVICE=cpu TMT_STEPS=20 TMT_CKPT=tmt.npz \
      TMT_DATA=data/alice_in_wonderland.txt \
      TMT_MULTIPLIERS=1,4 .venv/bin/python colab_lr_roles.py
"""
import base64
import gzip
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # repo root
OUT = os.path.dirname(os.path.abspath(__file__))                   # bundles/
MODULES = ["gpu_port.py", "train_gpu.py", "telemetry.py", "numpy_port.py",
           "tail_credit.py", "checkpoint_hub.py"]

DRIVER = r'''#!/usr/bin/env python3
"""Colab role-specific-LR factorial — generated by make_lr_roles_bundle.py.

Arms differ ONLY in the LR of the 8,192 per-layer `.decay` coordinates. For
each arm the script reports, from the engine's own telemetry:

  * grad_snr for the shared_trunk groups and for the decay groups
  * the decay-sigma health (mean/min/max sigma, hot-dim count, half-life)
  * throughput and any non-finite loss

and saves a tagged checkpoint so the laptop can ruler it. CE is judged on the
laptop afterwards -- this script never declares a winner, because a training-set
SNR move is not a held-out result.
"""
import base64
import glob, gzip, json, os, shutil, sys, time, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__)) if "__file__" in globals() else os.getcwd()
if not os.path.isdir(HERE):
    HERE = "/content" if os.path.isdir("/content") else os.getcwd()
PAYLOAD = __PAYLOAD__

TMT_TOKEN = os.environ.get("TMT_TOKEN", "")
if not TMT_TOKEN:
    try:
        from google.colab import userdata  # type: ignore
        TMT_TOKEN = userdata.get("TMT_TOKEN") or ""
    except Exception:
        pass
if TMT_TOKEN:
    os.environ["TMT_TOKEN"] = TMT_TOKEN
    print("[auth] TMT_TOKEN supplied at runtime (value not shown)", flush=True)

for name, b64 in PAYLOAD.items():
    with open(os.path.join(HERE, name), "wb") as f:
        f.write(gzip.decompress(base64.b64decode(b64)))
sys.path.insert(0, HERE)

import numpy as np
import torch
import gpu_port
import train_gpu as tg
import checkpoint_hub as hub

# ----------------------------- configuration ------------------------------
STEPS        = int(os.environ.get("TMT_STEPS", "30000"))
BATCH        = int(os.environ.get("TMT_BATCH", "1024"))
SAVE_EVERY   = int(os.environ.get("TMT_SAVE_EVERY", "20000"))
KEEP_K       = int(os.environ.get("TMT_KEEP_K", "2"))
LR           = float(os.environ.get("TMT_LR", "5e-4"))
# The axis under test. 1.0 is the CONTROL (identical to today's single-LR
# engine); the rest scale only the decay role.
MULTIPLIERS  = [float(x) for x in os.environ.get("TMT_MULTIPLIERS", "1,4,16").split(",")]
SEED         = int(os.environ.get("TMT_DATA_SEED", "0"))
DATA_MB      = int(os.environ.get("TMT_DATA_MB", "96"))
DATA_URL     = os.environ.get(
    "TMT_DATA_URL",
    "https://huggingface.co/datasets/roneneldan/TinyStories/resolve/main/"
    "TinyStories-train.txt")
HUB_REPO     = (os.environ.get("TMT_HUB_REPO") or os.environ.get("TMT_HUB_URL") or __REPO__)
CKPT         = os.environ.get("TMT_CKPT", "tmt_incumbent.npz")
DEVICE       = os.environ.get("TMT_DEVICE") or ("cuda" if torch.cuda.is_available() else "cpu")
TELEMETRY_EVERY = int(os.environ.get("TMT_TELEMETRY_EVERY", "2000"))
LOCAL_DATA   = os.environ.get("TMT_DATA", "")
PUSH         = os.environ.get("TMT_PUSH", "1") == "1"
FAILS = []


def banner(s):
    print("\n" + "=" * 74 + f"\n{s}\n" + "=" * 74, flush=True)


def result(name, ok, detail=""):
    FAILS.append(name) if not ok else None
    print(f"[RESULT] {name} = {'PASS' if ok else 'FAIL'}"
          + (f" ({detail})" if detail else ""), flush=True)


# ---------------- A: device ----------------
banner("A: device")
info = torch.cuda.get_device_name(0) if DEVICE == "cuda" else "cpu"
print(f"  device {DEVICE} ({info}) | torch {torch.__version__}", flush=True)
print(f"  gpu_port ring_credit=auto resolves to: "
      f"{gpu_port.GpuModel(device=DEVICE, dim=8, layers=1, seed=0).ring_credit}",
      flush=True)

# ---------------- B: incumbent checkpoint ----------------
banner("B: the incumbent checkpoint (pulled ONCE, every arm branches from it)")
start_t = None
ring_k = None
if os.path.exists(CKPT):
    print(f"  using local {CKPT}", flush=True)
else:
    try:
        hub.pull(CKPT, expect_t=None, require_digest=False)
        print(f"  pulled {CKPT}", flush=True)
    except Exception as exc:
        print(f"  [FATAL] could not obtain a checkpoint: {exc}", flush=True)
        sys.exit(1)
probe = np.load(CKPT)
start_t = int(np.ravel(probe["t"])[0])
ring_k = int(np.ravel(probe["ring_k"])[0])
ck_B = int(np.ravel(probe["B"])[0])
hot0 = sum(len(np.ravel(probe[f"tail_cols.{i}"]))
           for i in range(16) if f"tail_cols.{i}" in probe.files)
print(f"  t={start_t}  B={ck_B}  ring_k={ring_k}  hot dims={hot0}", flush=True)
result("checkpoint B matches --batch", ck_B == BATCH, f"{ck_B} vs {BATCH}")
if ck_B != BATCH:
    print(f"  [warn] resuming B={ck_B} into B={BATCH} resizes the recurrent "
          f"rows; arms stay matched with each other but are NOT comparable to "
          f"the B=1024 ruler rows", flush=True)

# ---------------- C: corpus, in-session ----------------
banner("C: corpus (one fetch, shared byte-for-byte by every arm)")
data_path = LOCAL_DATA
if not data_path:
    os.makedirs("corpus", exist_ok=True)
    data_path = os.path.join("corpus", f"tinystories_{DATA_MB}MB.txt")
    if not os.path.exists(data_path):
        print(f"  downloading {DATA_MB} MB from TinyStories ...", flush=True)
        with urllib.request.urlopen(DATA_URL, timeout=600) as r, \
                open(data_path, "wb") as f:
            n = 0
            while True:
                chunk = r.read(1 << 20)
                if not chunk:
                    break
                f.write(chunk)
                n += len(chunk)
                if n >= DATA_MB << 20:
                    break
print(f"  corpus: {data_path} ({os.path.getsize(data_path)/2**20:.0f} MB)",
      flush=True)

# ---------------- D: the factorial ----------------
banner(f"D: role-specific-LR factorial -- {len(MULTIPLIERS)} arms x {STEPS} steps")
print(f"  decay-role LR multipliers: {MULTIPLIERS}   (control = 1.0)", flush=True)
print(f"  every arm: same {start_t} checkpoint, same data seed {SEED}, "
      f"same {STEPS} steps, same B={BATCH}", flush=True)

summary = []
for mult in MULTIPLIERS:
    tag = f"lrdecay{mult:g}x"
    arm_path = f"arm_{tag}.npz"
    tele_path = f"telemetry_{tag}.jsonl"
    shutil.copyfile(CKPT, arm_path)          # every arm starts from identical bytes
    lrd = None if mult == 1.0 else LR * mult
    banner(f"ARM {tag}: --lr {LR:g} --lr-decay "
           f"{'unset (control)' if lrd is None else format(lrd, 'g')}")
    trainer = tg.Trainer(
        arm_path, batch=BATCH, save_every=SAVE_EVERY, keep_k=KEEP_K,
        tagged=True, max_steps=STEPS, data_seed=SEED, device=DEVICE,
        ring_credit="auto", lr=LR, lr_decay=lrd,
        telemetry_every=TELEMETRY_EVERY, telemetry_path=tele_path,
        log_every=max(2000, STEPS // 8))
    t0 = time.time()
    try:
        trainer.train(save=lambda m: m.save(arm_path), dataset=data_path,
                      hub_repo=None)
        ok = True
    except Exception as exc:
        print(f"  [FATAL] arm {tag} raised {type(exc).__name__}: {exc}",
              flush=True)
        ok = False
    dt = time.time() - t0
    row = {"arm": tag, "mult": mult, "lr_decay": lrd, "ok": ok,
           "seconds": round(dt, 1), "telemetry": tele_path, "ckpt": arm_path}
    if os.path.exists(tele_path):
        rows = [json.loads(x) for x in open(tele_path) if x.strip()]
        if rows:
            last = rows[-1]
            pg = last.get("parameter_groups", {})
            trunk = [g["grad_snr"] for k, g in pg.items()
                     if k.startswith("shared_trunk") and isinstance(g.get("grad_snr"), float)]
            dec = [g["grad_snr"] for k, g in pg.items()
                   if k.endswith(".decay") and isinstance(g.get("grad_snr"), float)]
            dl = last.get("decay_layers", [])
            row["snr_trunk"] = round(float(np.mean(trunk)), 4) if trunk else None
            row["snr_decay"] = round(float(np.mean(dec)), 4) if dec else None
            row["n_groups"] = len(pg)
            row["decay_sigma_mean"] = (round(float(np.mean([d["sigma_mean"] for d in dl])), 4)
                                       if dl else None)
            row["half_life_mean"] = (round(float(np.mean([d["half_life_mean_bytes"] for d in dl])), 3)
                                     if dl else None)
            row["hot_dims"] = last.get("hot_dimensions")
            row["state_rms"] = last.get("state_rms")
            row["throughput_B_per_s"] = last.get("throughput_B_per_s")
            row["final_t"] = last.get("t")
            print(f"  SNR trunk {row['snr_trunk']} | decay {row['snr_decay']} "
                  f"| sigma {row['decay_sigma_mean']} "
                  f"| half-life {row['half_life_mean']} | hot {row['hot_dims']} "
                  f"| {row['throughput_B_per_s']:,} B/s"
                  if row["throughput_B_per_s"] else "", flush=True)
    summary.append(row)
    result(f"arm {tag} completed", ok, f"{dt/60:.1f} min")

    # Push the arm's tagged checkpoint BEFORE moving on. `colab run` releases the
    # VM when it returns, and a checkpoint that never left is lost -- that is
    # exactly how the 2026-09-24 live leg lost its tags. Push by hand rather
    # than through trainer.train(hub_repo=...): that path PULLs first, and each
    # arm copy is deliberately older than the hub's newest tag, so the pull
    # would overwrite this arm with somebody else's checkpoint.
    if PUSH and os.path.exists(arm_path):
        for tp in (sorted(glob.glob(f"arm_{tag}_t*.npz")) or [arm_path]):
            try:
                st = hub.push(tp, repo_id=HUB_REPO, run_id=f"lrroles-{tag}")
                print(f"  [push] {os.path.basename(tp)} -> {HUB_REPO} (t={st})",
                      flush=True)
                row.setdefault("pushed", []).append(os.path.basename(tp))
            except Exception as exc:
                print(f"  [push] FAILED {os.path.basename(tp)}: "
                      f"{type(exc).__name__}: {exc}", flush=True)
                row["push_error"] = f"{type(exc).__name__}: {exc}"
                result(f"arm {tag} pushed", False, str(exc)[:70])
    elif not PUSH:
        print(f"  [push] disabled (TMT_PUSH=0): arm {tag} will NOT survive the "
              f"VM unless you download it", flush=True)

banner("SUMMARY")
print(json.dumps(summary, indent=2), flush=True)
with open("lr_roles_summary.json", "w") as f:
    json.dump(summary, f, indent=2)

banner("OVERALL")
print(f"[RESULT] OVERALL = {'FAIL ' + str(FAILS) if FAILS else 'PASS'}", flush=True)
print("""
NEXT -- this script does NOT declare a winner. A training-set SNR move is not a
held-out result. Pull each arm back on the laptop and ruler it:

    for m in 1 4 16; do
      .venv/bin/python tools/fs_verdict.py --pull --at-step <t> --dest runs/lrroles/m${m}x.npz
      .venv/bin/python tools/eval.py runs/lrroles/m${m}x.npz --slices 3 --bytes 20000 \\
          --xd-bytes 8000 --xd-files 4
    done

and compare every arm against the SAME-STEP control arm (the 1.0x one), which
is the only arm whose number answers "did the decay role want a different LR".
The bar is the plan's 0.03 CE, and no arm wins on CE alone -- read the
degeneracy metrics and the generation probe too.""", flush=True)
sys.exit(1 if FAILS else 0)
'''


def _repo():
    raw = (os.environ.get("TMT_HUB_REPO") or os.environ.get("TMT_HUB_URL")
           or "").strip().rstrip("/")
    if not raw:
        return "bakali1/tmt-checkpoints"
    for prefix in ("https://huggingface.co/", "http://huggingface.co/"):
        if raw.startswith(prefix):
            raw = raw[len(prefix):]
    parts = [p for p in raw.split("/") if p and p not in ("tree", "main", "datasets")]
    return "/".join(parts[:2]) if len(parts) >= 2 else raw


def main():
    payload = {}
    for name in MODULES:
        with open(os.path.join(HERE, name), "rb") as f:
            payload[name] = base64.b64encode(gzip.compress(f.read(), 9)).decode()
    out = DRIVER.replace("__PAYLOAD__", "{" + ", ".join(
        f"{k!r}: {v!r}" for k, v in payload.items()) + "}")
    out = out.replace("__REPO__", repr(_repo()))
    path = os.path.join(OUT, "colab_lr_roles.py")
    with open(path, "w") as f:
        f.write(out)
    print(f"wrote {path} ({os.path.getsize(path)/1024:.0f} KB) "
          "[no credentials embedded; supply TMT_TOKEN as a Colab secret]")
    print(f"  run: colab run --gpu T4 --timeout 7200 {os.path.relpath(path, HERE)}")


if __name__ == "__main__":
    main()