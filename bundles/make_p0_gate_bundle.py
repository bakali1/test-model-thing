#!/usr/bin/env python3
"""make_p0_gate_bundle.py -- ROADMAP P0 item 3, the credit-quality gate, on a T4.

    .venv/bin/python bundles/make_p0_gate_bundle.py
    colab run --gpu T4 --timeout 7200 bundles/colab_p0_gate.py
    colab exec <session> --script 'bash -c "cat /content/p0_gate_summary.json"'

TWO MATCHED FROM-SCRATCH ARMS, seed 0, data-seed 0, one byte-matched corpus,
judged at EQUAL WALL-CLOCK. The arms differ ONLY in the arm spec below.

    trace  the eligibility-trace trainer as it exists today (the baseline)
    cand   the candidate credit-assignment arm

Equal wall-clock is not a stylistic preference. #23's A/B style exists because
at equal STEPS a slower arm gets fewer bytes and the comparison silently
becomes a compute comparison. The driver therefore runs each arm, measures its
own wall clock, and writes it beside the checkpoint; tools/p0_verdict.py
REFUSES a verdict when the two arms are not inside its tolerance. Equal steps
alone is recorded too, as `steps`, but it is not the judgement.

This bundle trains and pushes. It does NOT run the ruler: the ruler needs the
held-out corpora (58 MB eval + 21 MB shift + the Gutenberg novels) and the
distance-curve cell is CPU-bound numpy that a Colab vCPU should not be asked
to do. Checkpoints are pushed from INSIDE the VM with the token arriving as
script_args -- the VM is GC'd even with --keep, and `colab download` dies with
IncompleteRead on ~142 MB files.

No credential is embedded in this file or in the bundle it generates, and
nothing is pushed unless --push-repo and --push-token are both supplied.
"""
import base64
import gzip
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

MODULES = ["gpu_port.py", "train_gpu.py", "telemetry.py", "numpy_port.py",
           "tail_credit.py", "checkpoint_hub.py",
           # distill.py / teacher_table.py are imported unconditionally by
           # train_gpu.py, so they travel whether or not this run uses them.
           # Shipping them is not touching the distillation path: the path is
           # closed and this run passes distill_alpha=0 (the Trainer default).
           "distill.py", "teacher_table.py"]
# tools/eval.py + tools/eval_npz.py travel so the SAME ruler code that judges
# the arms is what the bundle can run for a spot check, byte for byte.
TOOLS = ["eval.py", "eval_npz.py"]

# ---- the arm spec: the ONLY thing that differs between the two arms -------
# Each value is the kwargs handed to train_gpu.Trainer, so an arm is exactly
# the trainer plus a declared, printable delta. `trace` is the trainer as it
# stands. `cand` is the candidate means and is EMPTY in the shipped
# configuration.
#
# WHY IT IS EMPTY, stated here so it is not mistaken for an oversight: the
# only candidate credit-assignment means P0 ever named is P0 item 2, the
# hybrid window + trace trainer, which is HELD ("do not build on current
# evidence": the trace-quality gate found the trace exact, cosine 1.000000,
# rel 3.7e-07, so the conditional "if the gate shows the bias" never fired).
# Running this bundle as shipped therefore measures the TRACE TRAINER AGAINST
# ITSELF, which is the gate's null calibration: it establishes the smallest
# difference this harness can resolve, and it MUST return FAIL, because the
# pre-committed criteria (SNR up, long tail, no ruler regression) are not
# satisfiable by two arms that are the same estimator. A gate that cannot
# return FAIL on its own null has not been tested.
#
# To run a real candidate, put its kwargs in ARMS["cand"], e.g.
#     "cand": {"ring_k": 32}
# Nothing else needs to change and the harness does not need re-trusting.
ARMS = {
    "trace": {},
    "cand": {},
}

DRIVER = r'''#!/usr/bin/env python3
"""Colab P0 item 3 gate -- generated by make_p0_gate_bundle.py.

Two matched from-scratch arms, equal wall-clock, telemetry for the SNR leg.
Trains and pushes; the ruler runs locally in tools/p0_verdict.py."""
import base64
import gc
import gzip
import json
import os
import subprocess
import sys
import time
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__)) if "__file__" in globals() else os.getcwd()
if not os.path.isdir(HERE):
    HERE = "/content" if os.path.isdir("/content") else os.getcwd()
PAYLOAD = __PAYLOAD__
ARMS = __ARMS__

for name, b64 in PAYLOAD.items():
    path = os.path.join(HERE, name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(gzip.decompress(base64.b64decode(b64)))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "tools"))

STEPS = int(os.environ.get("TMT_STEPS", "10000"))
BATCH = int(os.environ.get("TMT_BATCH", "1024"))
DIM = int(os.environ.get("TMT_DIM", "512"))
LAYERS = int(os.environ.get("TMT_LAYERS", "16"))
LR = float(os.environ.get("TMT_LR", "5e-4"))
SEED = int(os.environ.get("TMT_SEED", "0"))
DATA_SEED = int(os.environ.get("TMT_DATA_SEED", "0"))
# Telemetry cadence. SNR's EMA is updated ONCE PER EMISSION, so this number is
# part of the SNR definition: the same run at --telemetry-every 1000 and at
# 250 produces two different quantities that both print as "snr". 250 over
# 10,000 steps gives 40 emissions, which is what the SNR leg's warm-up
# discard and paired SE need to be worth anything.
TELEMETRY_EVERY = int(os.environ.get("TMT_TELEMETRY_EVERY", "250"))
MEASURE_AFTER = int(os.environ.get("TMT_MEASURE_AFTER", "500"))
CORPUS = os.path.join(HERE, "corpus_000.txt")
CKPT_DIR = os.path.join(HERE, "ckpts")
DATA_URL = ("https://huggingface.co/datasets/roneneldan/TinyStories/resolve/"
            "main/TinyStories-train.txt")
# Spelled in hex ON PURPOSE. The 2026-10-04 KD bundle wrote this literal as
# plain bytes and it arrived as b"": blob.count(b"") is len(blob)+1 (it
# reported "stripped 16498690 markers" for a 16.5 MB corpus) and
# replace(b"", b"") is a no-op, so nothing was stripped and the dump refused
# the corpus. A literal that silently degrades to "" is a silent no-op.
MARKER = b"\x3c\x7c" + b"endoftext" + b"\x7c\x3e"

FAILS = []
PUSH_REPO = None
PUSH_TOKEN = None
for _i, _a in enumerate(sys.argv):
    if _a == "--push-repo" and _i + 1 < len(sys.argv):
        PUSH_REPO = sys.argv[_i + 1]
    if _a == "--push-token" and _i + 1 < len(sys.argv):
        PUSH_TOKEN = sys.argv[_i + 1]
PUSH_RUN = os.environ.get("TMT_RUN_ID", "p0-gate-2026-10-04")
if PUSH_REPO:
    os.environ["TMT_HUB_REPO"] = PUSH_REPO
    os.environ["TMT_HUB_REPO_TYPE"] = "model"
    os.environ["TMT_RUN_ID"] = PUSH_RUN
    print(f"  push target {PUSH_REPO} run_id {PUSH_RUN} (the token arrives as "
          f"argv and is never written into this file)", flush=True)

T0 = time.time()
SUMMARY = {
    "steps_requested": STEPS, "batch": BATCH, "dim": DIM, "layers": LAYERS,
    "lr": LR, "seed": SEED, "data_seed": DATA_SEED,
    "telemetry_every": TELEMETRY_EVERY, "measure_after": MEASURE_AFTER,
    "arms": {}, "arm_spec": ARMS,
}


def result(name, ok, detail=""):
    print(f"[RESULT] {name}: {'PASS' if ok else 'FAIL'} {detail}", flush=True)
    if not ok:
        FAILS.append(name)


def banner(s):
    print(f"\n===== {s} ===== ({time.time() - T0:.0f}s)", flush=True)


# ---------------- A: environment ----------------
banner("A: environment")
import numpy as np
import torch
print(f"  torch {torch.__version__} cuda={torch.cuda.is_available()}", flush=True)
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
if DEVICE == "cuda":
    print(f"  gpu {torch.cuda.get_device_name(0)}", flush=True)
result("cuda", DEVICE == "cuda", f"device={DEVICE}")
result("tf32-off", not (DEVICE == "cuda" and torch.backends.cuda.matmul.allow_tf32),
       "fp32 only; TF32 would break the parity contract")

# ---------------- B: corpus, byte-matched ----------------
banner("B: corpus (one byte stream, shared by both arms)")
# 1.45x (steps+200)*B: make_streams splits by line round-robin so the SHORTEST
# stream is ~0.767x the mean and an exactly-sized corpus runs ~23% short.
need = (STEPS + 200) * BATCH
want = int(need * 1.45)
if not os.path.exists(CORPUS) or os.path.getsize(CORPUS) < need:
    req = urllib.request.Request(DATA_URL, headers={
        "User-Agent": "tmt-p0-gate/1", "Range": f"bytes=0-{want}"})
    with urllib.request.urlopen(req, timeout=900) as r:
        blob = r.read()
    n_mark = blob.count(MARKER)
    blob = blob.replace(MARKER, b"")
    with open(CORPUS, "wb") as f:
        f.write(blob)
    print(f"  stripped {n_mark} control markers", flush=True)
sz = os.path.getsize(CORPUS)
print(f"  corpus {sz / 1e6:.2f} MB | need >= {need / 1e6:.2f} MB for {STEPS} "
      f"steps at B={BATCH}", flush=True)
result("corpus-size", sz >= need, f"{sz / 1e6:.2f} MB")
left = open(CORPUS, "rb").read().count(MARKER)
result("marker-stripped", len(MARKER) == 13 and left == 0,
       f"MARKER len={len(MARKER)} (want 13), occurrences left={left} (want 0)")
import hashlib
CORPUS_SHA = hashlib.sha256(open(CORPUS, "rb").read()).hexdigest()
print(f"  corpus sha256 {CORPUS_SHA[:16]} (recorded so both arms are provably "
      f"byte-matched)", flush=True)

# ---------------- C: the arms ----------------
banner(f"C: the two arms -- {STEPS} steps at B={BATCH}, seed {SEED}")
import numpy_port as np_
data = open(CORPUS, "rb").read()
streams, endss = np_.Runtime.make_streams(data, BATCH)
L = min(len(s) for s in streams) - 1
print(f"  L_step={L} | min stream bytes={min(len(s) for s in streams)}",
      flush=True)
run_steps = min(STEPS, L - 1)
result("steps-as-requested", run_steps == STEPS,
       f"ran {run_steps} of {STEPS} (L_step={L}); a shortfall means the "
       f"corpus slice was too short for B={BATCH}")
if run_steps < WARM_MIN := 5:
    sys.exit(f"[FATAL] L_step={L} at B={BATCH}: the corpus slice produced "
             f"{BATCH} streams too short to train on. Enlarge TMT_STEPS or "
             f"TMT_BATCH; do not silently run fewer steps than requested, "
             f"because an under-run arm would be compared against a full-run "
             f"one and the difference would be corpus, not credit quality.")
WARM = min(30, max(2, run_steps // 10))
os.makedirs(CKPT_DIR, exist_ok=True)
import train_gpu as tg


def arm(name, kwargs):
    """One matched from-scratch arm, with its own measured wall clock.

    The arms are run through train_gpu.Trainer.train() -- the repo's own
    trainer path, the one that produced every number in RESULTS.md -- rather
    than through a second hand-written loop. That matters for telemetry: the
    RunTelemetry object is constructed and stepped inside train(), so a
    hand-driven loop would either skip the SNR leg entirely or duplicate the
    wiring that defines it. One definition of the estimator, not two.

    Wall clock brackets the whole train() call with an explicit
    cuda.synchronize on both sides, because without one the asynchronous CUDA
    queue makes a 10k-step arm look like it took no time at all. The
    telemetry-measured steady-state seconds (first emission -> last emission,
    after --measure-after) are recorded too and are what the SNR leg quotes.
    """
    tel = os.path.join(CKPT_DIR, f"{name}.telemetry.jsonl")
    if os.path.exists(tel):
        os.remove(tel)
    t = tg.Trainer(path=os.path.join(CKPT_DIR, f"{name}.npz"),
                   batch=BATCH, max_steps=run_steps, device=DEVICE,
                   dim=DIM, layers=LAYERS, from_scratch=True, seed=SEED,
                   data_seed=DATA_SEED, lr=LR, warmup=WARM,
                   log_every=max(1, (run_steps - WARM) // 8), save_every=0,
                   keep_k=1, tagged=True,
                   telemetry_every=TELEMETRY_EVERY, telemetry_path=tel,
                   measure_after=MEASURE_AFTER, **dict(kwargs))
    if DEVICE == "cuda":
        torch.cuda.synchronize()
    t0 = time.time()
    t.train(True, CORPUS, None)
    if DEVICE == "cuda":
        torch.cuda.synchronize()
    wall = time.time() - t0

    events, secs, nbytes = [], None, None
    with open(tel) as f:
        for line in f:
            if not line.strip():
                continue
            e = json.loads(line)
            if e.get("event") == "interval":
                events.append(e)
                secs = e.get("throughput_measurement_seconds") or secs
                nbytes = e.get("bytes_seen")
    tags = sorted(f for f in os.listdir(CKPT_DIR)
                  if f.startswith(name + "_t") and f.endswith(".npz"))
    ck = os.path.join(CKPT_DIR, tags[-1]) if tags else \
        os.path.join(CKPT_DIR, f"{name}.npz")
    steady = (secs if secs else wall) or 1.0
    rec = {"wall_seconds": wall,
           "steady_state_seconds": secs,
           "steady_state_bytes": nbytes,
           "bytes": BATCH * (run_steps - WARM),
           "steps": run_steps - WARM,
           "seconds_per_step": steady / max(1, run_steps - WARM),
           "B_per_s": BATCH * (run_steps - WARM) / steady,
           "telemetry_emissions": len(events),
           "kwargs": dict(kwargs), "checkpoint": os.path.basename(ck),
           "telemetry": os.path.basename(tel)}
    print(f"  arm {name}: ce {t.model.last_ce:.4f} | WALL {wall:.1f} s "
          f"(steady-state {secs} s) for {rec['steps']:,} steps @ B={BATCH} "
          f"= {rec['B_per_s']:.0f} B/s | {len(events)} emissions", flush=True)
    del t
    gc.collect()
    if DEVICE == "cuda":
        torch.cuda.empty_cache()
    return rec


for nm, kw in ARMS.items():
    SUMMARY["arms"][nm] = arm(nm, kw)

# ---------------- D: equal wall-clock, checked HERE as well ----------------
# tools/p0_verdict.py refuses the verdict on this too. Checking it in the VM
# means a mismatch is caught while the run is still alive, not three hours
# later on a laptop.
banner("D: equal wall-clock")
secs = {k: v["wall_seconds"] for k, v in SUMMARY["arms"].items()}
spread = max(secs.values()) - min(secs.values())
rel = spread / max(secs.values())
for nm, rec in SUMMARY["arms"].items():
    print(f"  {nm:<8s} {rec['wall_seconds']:8.1f} s (steady "
          f"{rec['steady_state_seconds']} s) | {rec['steps']:>7,} steps | "
          f"{rec['bytes']:>13,} B | {rec['seconds_per_step'] * 1000:6.2f} "
          f"ms/step", flush=True)
print(f"  spread {spread:.1f} s = {100 * rel:.2f}%", flush=True)
result("equal-wall-clock", rel <= 0.02,
       f"{100 * rel:.2f}% spread between arms (tolerance 2%); equal STEPS "
       f"({SUMMARY['arms']['trace']['steps']:,} vs "
       f"{SUMMARY['arms']['cand']['steps']:,}) is recorded but is NOT the "
       f"judgement -- #23's A/B style is equal wall-clock")
SUMMARY["wall_spread_fraction"] = rel

# ---------------- E: SNR sanity, from the telemetry the arms wrote ----------
banner("E: the SNR leg's input exists (telemetry emitted)")
for nm, rec in SUMMARY["arms"].items():
    p = os.path.join(CKPT_DIR, rec["telemetry"])
    evs = []
    if os.path.exists(p):
        with open(p) as f:
            for line in f:
                if line.strip():
                    e = json.loads(line)
                    if e.get("event") == "interval":
                        evs.append(e)
    groups = sorted({g for e in evs for g in e.get("parameter_groups", {})})
    # The mean here is a SMOKE CHECK that the leg has an input, not the
    # verdict: tools/p0_verdict.py does the paired test on the same
    # telemetry. Warm-up 10 emissions are dropped because the EMA starts at
    # zero and is therefore biased low before it has history.
    trunks = [e["parameter_groups"]["shared_trunk"]["grad_snr"]
              for e in evs if "shared_trunk" in e.get("parameter_groups", {})]
    decs = [float(np.mean([v["grad_snr"] for k, v in e["parameter_groups"].items()
                           if k.endswith(".decay")]))
            for e in evs if any(k.endswith(".decay")
                                for k in e.get("parameter_groups", {}))]
    rec["telemetry_groups"] = groups
    rec["snr_trunk_mean"] = float(np.mean(trunks[10:])) if len(trunks) > 10 else None
    rec["snr_decay_mean"] = float(np.mean(decs[10:])) if len(decs) > 10 else None
    print(f"  {nm}: {len(evs)} emissions every {TELEMETRY_EVERY} steps, "
          f"{len(groups)} groups | trunk SNR (after 10 warm-up) "
          f"{rec['snr_trunk_mean']} | decay SNR {rec['snr_decay_mean']}",
          flush=True)
    result(f"telemetry-{nm}", len(evs) >= 10,
           f"{len(evs)} emissions; SNR is a TRAINING-TIME quantity and cannot "
           f"be recovered from the checkpoint afterwards")
    if rec["snr_trunk_mean"] is not None:
        print(f"      [defn] snr = ||EMA(g)||^2/EMA(||g||^2), EMA decay 0.9, "
              f"updated once per emission = every {TELEMETRY_EVERY} steps; "
              f"floor 0 (zero gradient), ceiling 1", flush=True)

# ---------------- F: push from inside the VM ----------------
# The VM is GC'd even with --keep and `colab download` dies with
# IncompleteRead on ~142 MB files, so anything that must survive leaves the
# VM DURING the run. The token arrives as script_args; it is not written into
# the bundle, the summary, or any log line.
if PUSH_REPO:
    banner("F: push checkpoints from inside the VM")
    import checkpoint_hub
    for nm, rec in SUMMARY["arms"].items():
        src = os.path.join(CKPT_DIR, rec["checkpoint"])
        try:
            tt = checkpoint_hub.push(src, repo_id=PUSH_REPO, token=PUSH_TOKEN,
                                     repo_type="model", run_id=PUSH_RUN)
            rec["pushed"] = {"repo": PUSH_REPO, "t": tt,
                             "name": rec["checkpoint"]}
            print(f"  pushed {nm} t={tt}", flush=True)
        except Exception as exc:
            print(f"  push FAILED for {nm}: {type(exc).__name__} {exc}", flush=True)
            FAILS.append("push-" + nm)
    with open(os.path.join(HERE, "p0_gate_summary.json"), "w") as f:
        json.dump(SUMMARY, f, indent=2)
else:
    print("\n  (no --push-repo given; checkpoints stay on the VM and will be "
          "GC'd)", flush=True)

print(f"\n  total wall: {time.time() - T0:.0f}s", flush=True)
print(f"[RESULT] OVERALL: {'PASS' if not FAILS else 'FAIL - ' + ', '.join(FAILS)}",
      flush=True)
print("[RESULT] This is the TRAINING half of the gate only. The verdict is "
      "rendered locally by tools/p0_verdict.py, which is where the three "
      "legs and the equal-wall-clock refusal live.", flush=True)
print("[RESULT] NOTHING in this summary is a PASS for P0 item 3. The gate "
      "returns PASS/FAIL/PARTIAL from tools/p0_verdict.py, and the two arms "
      "as shipped are the SAME estimator, so the expected verdict is FAIL.",
      flush=True)
'''

REPO = os.environ.get("TMT_HUB_REPO", "")


def main():
    payload = {}
    for name in MODULES:
        with open(os.path.join(ROOT, name), "rb") as fh:
            payload[name] = base64.b64encode(gzip.compress(fh.read())).decode()
    for name in TOOLS:
        with open(os.path.join(ROOT, "tools", name), "rb") as fh:
            payload[os.path.join("tools", name)] = \
                base64.b64encode(gzip.compress(fh.read())).decode()
    driver = (DRIVER.replace("__PAYLOAD__", repr(payload))
                      .replace("__ARMS__", json.dumps(ARMS))
                      .replace("__REPO__", repr(REPO)))
    out = os.path.join(HERE, "colab_p0_gate.py")
    with open(out, "w") as fh:
        fh.write(driver)
    print(f"wrote {out} ({os.path.getsize(out) / 1e6:.2f} MB)")
    print(f"  run: colab run --gpu T4 --timeout 7200 bundles/colab_p0_gate.py")
    print(f"  arms: {json.dumps(ARMS)}")
    if ARMS["cand"] == []:
        print("  NOTE: the candidate arm spec is EMPTY, so this run is the "
              "gate's NULL CALIBRATION --\n        the trace trainer against "
              "itself. It MUST return FAIL. See the header of this file for "
              "why\n        (P0 item 2, the only candidate means P0 ever named, "
              "is HELD).")
    print(f"  default {STEPS_DEFAULT} steps at B=1024, seed 0, data-seed 0, "
          f"telemetry every 250 steps")
    print("  embeds NO credentials; pushes nothing unless --push-repo AND "
          "--push-token are passed")


STEPS_DEFAULT = 10000

if __name__ == "__main__":
    main()