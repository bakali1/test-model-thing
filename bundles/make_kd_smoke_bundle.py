REPO = os.environ.get("TMT_HUB_REPO", "")


def main():
    payload = {}
    for name in MODULES:
        with open(os.path.join(ROOT, name), "rb") as fh:
            payload[name] = base64.b64encode(gzip.compress(fh.read())).decode()
    for name in TOOLS:
        src = os.path.join(ROOT, "tools", name)
        if not os.path.exists(src):          # teacher_table moved to the root
            src = os.path.join(ROOT, name)
        key = os.path.join("tools", name)
        with open(src, "rb") as fh:
            payload[key] = base64.b64encode(gzip.compress(fh.read())).decode()
    driver = DRIVER.replace("__PAYLOAD__", repr(payload)).replace("__REPO__", repr(REPO))
    out = os.path.join(HERE, "colab_kd_smoke.py")
    with open(out, "w") as fh:
        fh.write(driver)
    size = os.path.getsize(out)
    print(f"wrote {out} ({size / 1e6:.2f} MB)")
    print(f"  embedded: {', '.join(MODULES + [os.path.join('tools', t) for t in TOOLS])}")
    print("  run: colab run --gpu T4 --timeout 2700 bundles/colab_kd_smoke.py")
    print("  it embeds NO credentials and pushes nothing (teacher + corpus are public)")


if __name__ == "__main__":
    main()
