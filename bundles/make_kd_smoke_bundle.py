# ---------------- D: corpus slice ----------------
banner("D: corpus slice")
need = (STEPS + 64) * BATCH
if not os.path.exists(CORPUS) or os.path.getsize(CORPUS) < need:
    want = max(CORPUS_MB * 1_000_000, need * 3)
