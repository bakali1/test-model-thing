def leg(alpha, steps):
    t = tg.Trainer(path=os.path.join(HERE, f"smoke_a{alpha}.npz"),
                   batch=BATCH, max_steps=steps, device=DEVICE,
                   dim=512, layers=16, from_scratch=True, seed=0,
                   log_every=10 ** 9, save_every=0, tagged=False,
                   distill_dir=DUMP if alpha > 0 else None,
                   distill_alpha=alpha, distill_block=32,
                   distill_repo=TEACHER, warmup=30)
    mdl = t.model
    mdl.new_states(BATCH)
    t._kd_provider(CORPUS, mdl)
    warm = min(30, max(2, steps // 10))
    for i in range(warm):
        mdl.step_batch(mats[i], mats[i + 1], ets[i])
    if DEVICE == "cuda":
        torch.cuda.synchronize()
    t0 = time.time()
    loss = 0.0
    for i in range(warm, warm + steps):
        loss = float(mdl.step_batch(mats[i], mats[i + 1], ets[i]))
    if DEVICE == "cuda":
        torch.cuda.synchronize()
    dt = time.time() - t0
    return loss, dt / steps, mdl.kd_stats(), t


print("  --- timing CE-only (alpha=0) ---", flush=True)
