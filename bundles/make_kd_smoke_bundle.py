#!/usr/bin/env python3
"""make_kd_smoke_bundle.py — the 2,000-step distillation SMOKE, on a T4.

    .venv/bin/python bundles/make_kd_smoke_bundle.py
    colab run --gpu T4 --timeout 2700 bundles/colab_kd_smoke.py

This is NOT a science arm. It trains nothing worth reporting; it proves the KD
path works end to end on a real GPU with the frozen configuration, and it
reports the numbers that decide whether the science arms are worth T4 quota:

  * the dump's real storage cost in B/token (frozen target 193)
  * retained prefix mass and KD coverage per byte depth — the statistic that
    says how much of the model actually receives a teacher signal
  * throughput with and without the KD term, so the +1.5 % measured on the
    laptop CPU is confirmed (or refuted) on a T4
  * gate 3 on CUDA: alpha=0 must be bit-identical to a no-provider run

It calls the REAL command-line tools (`tools/mi_dump.py`, `tools/mi_report.py`,
`train_gpu.py`) via sys.argv rather than reimplementing them, so the smoke
exercises the same code the science arms will.

No credentials: the teacher and the corpus are both public. The generated file
embeds no token, and nothing is pushed to the hub.
"""
