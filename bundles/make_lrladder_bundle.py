def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--arm", required=True, choices=sorted(ARMS),
                    help="which single arm to emit")
    args = ap.parse_args()
    arm = ARMS[args.arm]

    payload = {}
    for name in MODULES:
        with open(os.path.join(ROOT, name), "rb") as fh:
            payload[name] = base64.b64encode(gzip.compress(fh.read())).decode()

    driver = (DRIVER
              .replace("__PAYLOAD__", repr(payload))
              .replace("__ARM_NAME__", repr(args.arm))
              .replace("__ARM_LR__", repr(arm["lr"]))
              .replace("__ARM_LABEL__", repr(arm["label"]))
              .replace("__STEPS__", str(STEPS))
              .replace("__BATCH__", str(BATCH))
              .replace("__DIM__", str(DIM))
              .replace("__LAYERS__", str(LAYERS))
              .replace("__SEED__", str(SEED))
              .replace("__DATA_SEED__", str(DATA_SEED))
              .replace("__TELEMETRY_EVERY__", str(TELEMETRY_EVERY))
              .replace("__MEASURE_AFTER__", str(MEASURE_AFTER)))
    # The remaining placeholders must all be gone; a leftover one would ship a
    # bundle that dies at import.
    for leftover in ("__PAYLOAD__", "__ARM_NAME__", "__ARM_LR__", "__ARM_LABEL__",
                     "__STEPS__", "__BATCH__", "__DIM__", "__LAYERS__",
                     "__SEED__", "__DATA_SEED__", "__TELEMETRY_EVERY__",
                     "__MEASURE_AFTER__"):
        assert leftover not in driver, f"unsubstituted placeholder {leftover}"

    out = os.path.join(HERE, f"colab_lrladder_{args.arm}.py")
    with open(out, "w") as fh:
        fh.write(driver)
    print(f"wrote {out} ({os.path.getsize(out) / 1e6:.2f} MB)")
    print(f"  arm {args.arm}: {arm['label']}")
    print(f"  {STEPS} steps at B={BATCH}, seed {SEED}, data-seed {DATA_SEED}, "
          f"tf32 off, telemetry every {TELEMETRY_EVERY} steps")
    print(f"  corpus: TinyStories-train.txt, first "
          f"{int((STEPS + 200) * BATCH * 1.45 / 1e6)} MB, sha256 recorded "
          f"in the summary so A and B are provably byte-matched")
    print(f"  run: colab run --gpu T4 --timeout 7200 {out} "
          f"-- --push-repo <repo> --push-token \"$T\"")
    print("  embeds NO credentials; pushes nothing unless BOTH --push-repo and "
          "--push-token are passed")


if __name__ == "__main__":
    main()